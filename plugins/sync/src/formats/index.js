// The format registry. A format turns synced data into files (paths relative to the channel's
// output directory); the engine decides what is written, kept or removed.
//   scope "process": render({ item, channel, atlasModel, host }) once per selected process
//   scope "channel": render({ items, channel, state, host }) once per run over all processes
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { architectureFormat } from "./architecture.js";
import { markdownCell, stableStringify } from "../util.js";

const documentsFormat = {
  id: "documents",
  scope: "process",
  async render({ item, options }) {
    const types = options.types;
    const files = item.documents
      .filter(({ type }) => !types?.length || types.includes(type))
      .map(({ file, data }) => ({ path: `${item.key}/${file}`, content: data }));
    return { files, warnings: files.length ? [] : [`${item.key}: no documents (only a fact sheet was provided)`] };
  }
};

const factsFormat = {
  id: "facts",
  scope: "process",
  async render({ item }) {
    return { files: [{ path: `${item.key}/facts.json`, content: `${stableStringify(item.facts, 2)}\n` }], warnings: [] };
  }
};

const uiTestsFormat = {
  id: "ui-tests",
  scope: "process",
  async render({ item }) {
    const test = item.documents.find(({ type }) => type === "ui-test");
    if (!test) return { files: [], warnings: [`${item.key}: no BC Atlas UI test in the snapshot`] };
    return { files: [{ path: `${item.key}.Codeunit.al`, content: test.data }], warnings: [] };
  }
};

const cell = markdownCell;

const indexFormat = {
  id: "index",
  scope: "channel",
  async render({ items, channel }) {
    const rows = items.map((item) => ({
      key: item.key,
      process: item.process,
      feature: item.feature,
      snapshot: item.snapshotNo,
      fingerprint: item.fingerprint,
      drift: item.driftDetected,
      phases: (item.facts.phases ?? []).map(({ phase, title }) => ({ phase, title })),
      clicks: (item.facts.uiSteps ?? []).length,
      technicalSteps: (item.facts.technicalSteps ?? []).length,
      tables: (item.facts.tables ?? []).map(({ tableId, tableName }) => ({ tableId, tableName })),
      documents: item.documents.map(({ file }) => file).sort()
    }));
    const features = [...new Set(rows.map(({ feature }) => feature))].sort();
    const md = [`# Synced processes (${channel.id})`, ""];
    if (channel.description) md.push(channel.description, "");
    md.push("Generated by bc-atlas-sync from Business Central fact snapshots. Do not edit: re-record the process and sync again.", "");
    for (const feature of features) {
      md.push(`## ${feature}`, "");
      md.push("| Process | Snapshot | Phases | Clicks | Tables | Fingerprint | Drift |", "|---|---:|---|---:|---:|---|---|");
      for (const row of rows.filter((item) => item.feature === feature)) {
        const link = row.documents.length ? `[${cell(row.process)}](${row.key}/${row.documents.includes("layered.md") ? "layered.md" : row.documents[0]})` : cell(row.process);
        md.push(`| ${link} | ${row.snapshot} | ${row.phases.map(({ title }) => cell(title)).join(" → ") || "-"} | ${row.clicks} | ${row.tables.length} | \`${String(row.fingerprint).slice(0, 12)}\` | ${row.drift ? "**changed**" : "-"} |`);
      }
      md.push("");
    }
    return {
      files: [
        { path: "index.md", content: md.join("\n") },
        { path: "index.json", content: `${stableStringify({ schema: "bc-atlas-sync.index/1", channel: channel.id, processes: rows }, 2)}\n` }
      ],
      warnings: []
    };
  }
};

async function readTree(dir, base = dir) {
  const files = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await readTree(full, base));
    else files.push({ path: path.relative(base, full).split(path.sep).join("/"), content: await fs.readFile(full) });
  }
  return files;
}

const atlasDocsFormat = {
  id: "atlas-docs",
  scope: "channel",
  async render({ items, host, options }) {
    if (typeof host?.renderDocs !== "function") {
      return { files: [], warnings: ["atlas-docs needs BC Atlas: run the channel with \"bca sync run\" or the sync task of \"bca run\""] };
    }
    const tests = items.map((item) => ({ item, test: item.documents.find(({ type }) => type === "ui-test") })).filter(({ test }) => test);
    if (!tests.length) return { files: [], warnings: ["atlas-docs: no BC Atlas UI tests in the synced snapshots"] };
    const work = await fs.mkdtemp(path.join(os.tmpdir(), "bc-atlas-sync-"));
    try {
      const testsDir = path.join(work, "tests");
      const outputDir = path.join(work, "out");
      await fs.mkdir(testsDir, { recursive: true });
      for (const { item, test } of tests) await fs.writeFile(path.join(testsDir, `${item.key}.Codeunit.al`), test.data);
      const result = await host.renderDocs({
        testsDir,
        outputDir,
        formats: options.export ?? ["markdown"],
        mode: options.as ?? "guide",
        language: options.language,
        title: options.title
      });
      const files = (await readTree(outputDir)).map((file) => ({ ...file, path: `atlas/${file.path}` }));
      return { files, warnings: result?.warnings ?? [] };
    } finally {
      await fs.rm(work, { recursive: true, force: true });
    }
  }
};

export const FORMAT_IMPLEMENTATIONS = new Map(
  [documentsFormat, factsFormat, uiTestsFormat, architectureFormat, indexFormat, atlasDocsFormat].map((format) => [format.id, format])
);
