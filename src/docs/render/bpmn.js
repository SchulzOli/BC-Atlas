// BPMN 2.0 XML for a use-case process: a collaboration with one pool, a lane
// per permission set, and a collapsed sub-process per scenario whose clicks
// are on their own diagram plane (drill-down in Camunda Modeler and bpmn.io).
// Diagram interchange (DI) comes from the same layout as the SVG preview, and
// colors use the BPMN in Color extension that modelers understand.
import { layoutProcess } from "../process.js";
import { COLORS } from "./process-svg.js";
import { escapeXml } from "./format.js";

const ELEMENT = {
  start: "startEvent",
  end: "endEvent",
  event: "intermediateThrowEvent",
  task: "task",
  subprocess: "subProcess",
  gateway: "exclusiveGateway"
};

function tag(node) {
  return node.kind === "task" && node.user ? "userTask" : ELEMENT[node.kind];
}

function attributes(values) {
  return Object.entries(values)
    .filter(([, value]) => value !== undefined && value !== "")
    .map(([key, value]) => ` ${key}="${escapeXml(String(value))}"`).join("");
}

function flowElements(process, indent) {
  const pad = " ".repeat(indent);
  const lines = [];
  const incoming = (id) => process.flows.filter(({ to }) => to === id).map(({ id: flow }) => flow);
  const outgoing = (id) => process.flows.filter(({ from }) => from === id).map(({ id: flow }) => flow);
  for (const node of process.nodes) {
    const name = tag(node);
    const children = [];
    if (node.documentation) children.push(`${pad}  <bpmn:documentation>${escapeXml(node.documentation)}</bpmn:documentation>`);
    for (const flow of incoming(node.id)) children.push(`${pad}  <bpmn:incoming>${flow}</bpmn:incoming>`);
    for (const flow of outgoing(node.id)) children.push(`${pad}  <bpmn:outgoing>${flow}</bpmn:outgoing>`);
    if (node.loop) children.push(`${pad}  <bpmn:standardLoopCharacteristics />`);
    if (node.child) children.push(...flowElements(node.child, indent + 2));
    const open = `${pad}<bpmn:${name}${attributes({ id: node.id, name: node.name })}`;
    lines.push(children.length ? `${open}>\n${children.join("\n")}\n${pad}</bpmn:${name}>` : `${open} />`);
  }
  for (const flow of process.flows) {
    lines.push(`${pad}<bpmn:sequenceFlow${attributes({ id: flow.id, name: flow.name, sourceRef: flow.from, targetRef: flow.to })} />`);
  }
  return lines;
}

function colors(kind) {
  const color = COLORS[kind] ?? COLORS.task;
  return ` color:background-color="${color.fill}" color:border-color="${color.stroke}"`;
}

function bounds(box) {
  return `<dc:Bounds x="${Math.round(box.x)}" y="${Math.round(box.y)}" width="${Math.round(box.width)}" height="${Math.round(box.height)}" />`;
}

function shapes(layout, pad) {
  const lines = [];
  for (const node of layout.process.nodes) {
    const box = layout.bounds.get(node.id);
    const expanded = node.kind === "subprocess" ? ` isExpanded="false"` : "";
    const label = ["start", "end", "event"].includes(node.kind) && node.name
      ? `\n${pad}  <bpmndi:BPMNLabel>${bounds({ x: box.x - 47, y: box.y + box.height + 4, width: 130, height: 40 })}</bpmndi:BPMNLabel>`
      : "";
    const marker = node.kind === "gateway" ? ` isMarkerVisible="true"` : "";
    lines.push(`${pad}<bpmndi:BPMNShape id="${node.id}_di" bpmnElement="${node.id}"${expanded}${marker}${colors(node.kind)}>`,
      `${pad}  ${bounds(box)}${label}`, `${pad}</bpmndi:BPMNShape>`);
  }
  for (const flow of layout.process.flows) {
    lines.push(`${pad}<bpmndi:BPMNEdge id="${flow.id}_di" bpmnElement="${flow.id}">`,
      ...layout.waypoints.get(flow.id).map(([x, y]) => `${pad}  <di:waypoint x="${Math.round(x)}" y="${Math.round(y)}" />`),
      `${pad}</bpmndi:BPMNEdge>`);
  }
  return lines;
}

/**
 * @param process result of useCaseProcess()
 * @param options { version } exporter version
 */
export function renderBpmn(process, { version = "" } = {}) {
  const layout = layoutProcess(process);
  const collaboration = `Collaboration_${process.id.replace(/^Process_/u, "")}`;
  const lines = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!-- Generated by BC Atlas docs from AL UI tests. Regenerate instead of editing. -->`,
    `<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL" xmlns:bpmndi="http://www.omg.org/spec/BPMN/20100524/DI" xmlns:dc="http://www.omg.org/spec/DD/20100524/DC" xmlns:di="http://www.omg.org/spec/DD/20100524/DI" xmlns:color="http://www.omg.org/spec/BPMN/non-normative/color/1.0"${attributes({
      id: `Definitions_${process.id.replace(/^Process_/u, "")}`,
      targetNamespace: "https://schulzoli.github.io/BC-Atlas/bpmn",
      exporter: "BC Atlas",
      exporterVersion: version
    })}>`,
    `  <bpmn:collaboration id="${collaboration}">`,
    `    <bpmn:participant${attributes({ id: process.participant, name: process.name, processRef: process.id })} />`,
    `  </bpmn:collaboration>`,
    `  <bpmn:process${attributes({ id: process.id, name: process.name })} isExecutable="false">`
  ];
  if (process.lanes.length) {
    lines.push(`    <bpmn:laneSet id="LaneSet_${process.id.replace(/^Process_/u, "")}">`);
    for (const lane of process.lanes) {
      lines.push(`      <bpmn:lane${attributes({ id: lane.id, name: lane.name })}>`,
        ...process.nodes.filter((node) => node.lane === lane.id).map((node) => `        <bpmn:flowNodeRef>${node.id}</bpmn:flowNodeRef>`),
        `      </bpmn:lane>`);
    }
    lines.push(`    </bpmn:laneSet>`);
  }
  lines.push(...flowElements(process, 4), `  </bpmn:process>`);

  lines.push(`  <bpmndi:BPMNDiagram id="BPMNDiagram_${collaboration}">`,
    `    <bpmndi:BPMNPlane id="BPMNPlane_${collaboration}" bpmnElement="${collaboration}">`);
  if (layout.pool) {
    lines.push(`      <bpmndi:BPMNShape id="${process.participant}_di" bpmnElement="${process.participant}" isHorizontal="true">`,
      `        ${bounds(layout.pool)}`, `      </bpmndi:BPMNShape>`);
    for (const lane of layout.lanes) {
      lines.push(`      <bpmndi:BPMNShape id="${lane.id}_di" bpmnElement="${lane.id}" isHorizontal="true">`,
        `        ${bounds(lane)}`, `      </bpmndi:BPMNShape>`);
    }
  }
  lines.push(...shapes(layout, "      "), `    </bpmndi:BPMNPlane>`, `  </bpmndi:BPMNDiagram>`);
  for (const node of process.nodes.filter(({ child }) => child)) {
    lines.push(`  <bpmndi:BPMNDiagram id="BPMNDiagram_${node.id}">`,
      `    <bpmndi:BPMNPlane id="BPMNPlane_${node.id}" bpmnElement="${node.id}">`,
      ...shapes(layoutProcess(node.child), "      "),
      `    </bpmndi:BPMNPlane>`, `  </bpmndi:BPMNDiagram>`);
  }
  lines.push(`</bpmn:definitions>`, "");
  return lines.join("\n");
}
