import { label, phrase } from "../phrases.js";
import { inlineStep } from "../steps.js";
import { hasRunbook, humanizeFeature, sameAsTitle } from "../task.js";
import { escapeMarkdown, markdown } from "./format.js";

const LINK_HEADINGS = { next: "heading.next", related: "heading.related", alternative: "heading.alternative" };
const RUNBOOK_HEADINGS = { monitor: "heading.monitor", recovery: "heading.recovery", troubleshoot: "heading.troubleshoot" };

/** [MONITOR], [RECOVERY], and [TROUBLESHOOT] under headings of the given level. */
function runbookLines(task, level) {
  const lines = [];
  for (const [key, heading] of Object.entries(RUNBOOK_HEADINGS)) {
    if (task.runbook[key].length) {
      lines.push(`${"#".repeat(level)} ${label(task.language, heading)}`, "", ...task.runbook[key].map((item) => `- ${md([item])}`), "");
    }
  }
  return lines;
}

function performedBy(task) {
  return task.roles.length ? [label(task.language, "label.performed-by", { who: task.roles.join(", ") }), ""] : [];
}

function link(target, extension = ".md") {
  return target.exists ? `[${escapeMarkdown(target.title)}](./${target.id}${extension})` : `**${escapeMarkdown(target.id)}**`;
}

// Tag text is author prose: escape it so `<Posted>`, `*now*` or `a | b` render as written.
function md(value) {
  return markdown(value, { escape: true });
}

// Pipes that md() or escapeMarkdown() already escaped stay as they are.
function cell(value) {
  return String(value ?? "").replace(/(?<!\\)\|/gu, "\\|").replace(/\r?\n/gu, " ");
}

function textCell(value) {
  return cell(escapeMarkdown(value));
}

function header(task) {
  return [
    `<!-- Generated by BC Atlas docs from ${task.source.file}#${task.source.procedure}. Do not edit this file. -->`,
    `<!-- Source SHA-256: ${task.source.hash} -->`,
    ""
  ];
}

function sourceDetails(task) {
  const { language } = task;
  return [
    "<details>",
    `<summary>${label(language, "heading.source")}</summary>`,
    "",
    `- ${label(language, "label.file")}: \`${task.source.file}\``,
    `- ${label(language, "label.function")}: \`${task.source.procedure}\``,
    `- ${label(language, "label.hash")}: \`${task.source.hash}\``,
    "",
    "</details>",
    ""
  ];
}

function prereqLine(item, language) {
  if (item.kind === "requires") return phrase(language, "label.requires", { guide: { raw: link(item.link) } });
  return item.tokens;
}

function mdTokens(tokens) {
  return tokens.map((token) => (token?.raw !== undefined ? token.raw : md([token]))).join("");
}

function withInfo(step) {
  return `${md(step.cmd)}${step.outcome ? ` ${md(step.outcome)}` : ""}${step.info ? ` _${escapeMarkdown(step.info)}_` : ""}`;
}

function stepLines(step, indent) {
  const pad = " ".repeat(indent);
  const lines = [];
  for (const item of step.items ?? []) {
    lines.push(`${pad}- ${withInfo(item)}`);
    for (const nested of item.items ?? []) lines.push(`${pad}  - ${withInfo(nested)}`);
  }
  return lines;
}

function flowSection(task, flowImage) {
  if (!flowImage) return [];
  const heading = label(task.language, "heading.flow");
  return [`## ${heading}`, "", `![${escapeMarkdown(task.title)}](./${flowImage})`, ""];
}

/** User guide in the shape of a DITA task: prerequisites, steps, result, links. */
export function renderGuide(task, { flowImage } = {}) {
  const { language } = task;
  const lines = [...header(task), `# ${escapeMarkdown(task.title)}`, "", md(task.shortdesc), "", ...performedBy(task), ...flowSection(task, flowImage)];
  if (task.prereqs.length) {
    lines.push(`## ${label(language, "heading.prereq")}`, "",
      ...task.prereqs.map((item) => `- ${mdTokens(prereqLine(item, language))}`), "");
  }
  if (task.steps.length) {
    lines.push(`## ${label(language, "heading.steps")}`, "");
    if (task.examples) lines.push(`> ${label(language, "label.examples")}`, "");
    for (const [index, step] of task.steps.entries()) {
      lines.push(`${index + 1}. ${withInfo(step)}`, ...stepLines(step, 3));
      if (step.result?.length) {
        lines.push("", `   ${md(phrase(language, "label.step-result", { result: step.result.join(" ") }))}`, "");
      }
    }
    lines.push("");
  }
  lines.push(`## ${label(language, "heading.result")}`, "", ...task.result.map((item) => `- ${escapeMarkdown(item)}`), "");
  if (hasRunbook(task)) lines.push(`## ${label(language, "heading.support")}`, "", ...runbookLines(task, 3));
  for (const [kind, heading] of Object.entries(LINK_HEADINGS)) {
    if (task.links[kind].length) {
      lines.push(`## ${label(language, heading)}`, "", ...task.links[kind].map((target) => `- ${link(target)}`), "");
    }
  }
  lines.push(...sourceDetails(task));
  return lines.join("\n").replace(/\n{3,}/gu, "\n\n");
}

/**
 * Flattens a task into numbered test-case rows: { action, expected }.
 * Preconditions become the first row so the table works on its own.
 */
export function testCaseRows(task) {
  const { language } = task;
  const rows = [];
  if (task.prereqs.length) {
    rows.push({
      action: phrase(language, "testcase.check-preconditions"),
      expected: phrase(language, "testcase.preconditions-met")
    });
  }
  for (const step of task.steps) {
    // A loop or a dialog is one row, so its context ("For each ...", "If the ... page opens") stays.
    if (step.items?.length && !step.phase) {
      rows.push({ action: inlineStep(step, language), expected: step.expected ?? [] });
    } else if (step.items?.length) {
      for (const item of step.items) {
        rows.push({
          action: item.items?.length ? inlineStep(item, language) : item.cmd,
          expected: item.expected ?? []
        });
      }
      const last = rows.at(-1);
      if (step.result?.length || step.expected?.length) last.expected = step.result?.length ? [step.result.join(" ")] : step.expected;
    } else {
      rows.push({ action: step.cmd, expected: step.expected ?? [] });
    }
  }
  if (rows.length && task.result.length) rows.at(-1).expected = [task.result.join(" ")];
  return rows;
}

/** Test-case specification with an executable step table and sign-off block. */
export function renderTestCase(task, { flowImage } = {}) {
  const { language } = task;
  const t = (key, values) => label(language, key, values);
  const lines = [...header(task), `# ${t("testcase.title", { id: task.id })}: ${escapeMarkdown(task.title)}`, ""];
  lines.push(
    "| | |",
    "| --- | --- |",
    `| ${t("testcase.id")} | \`${task.id}\` |`,
    `| ${t("testcase.objective")} | ${textCell(task.goal)} |`
  );
  if (task.features.length) lines.push(`| ${t("label.use-case")} | ${textCell(task.features.map(humanizeFeature).join(", "))} |`);
  if (task.roles.length) lines.push(`| ${t("column.role")} | ${textCell(task.roles.join(", "))} |`);
  if (task.permissions.length) lines.push(`| ${t("testcase.permissions")} | ${textCell(task.permissions.join(", "))} |`);
  lines.push(`| ${t("testcase.source")} | \`${task.source.file}#${task.source.procedure}\` |`, "");
  lines.push(...flowSection(task, flowImage));

  const preconditions = task.prereqs.filter(({ kind }) => kind !== "permission");
  if (preconditions.length) {
    lines.push(`## ${t("testcase.preconditions")}`, "",
      ...preconditions.map((item) => `- ${mdTokens(prereqLine(item, language))}`), "");
  }
  lines.push(
    `## ${t("testcase.steps")}`,
    "",
    `| ${t("testcase.step")} | ${t("testcase.action")} | ${t("testcase.expected")} | ${t("testcase.pass")} | ${t("testcase.actual")} |`,
    "| ---: | --- | --- | :---: | --- |",
    ...testCaseRows(task).map((row, index) =>
      `| ${index + 1} | ${cell(md(row.action))} | ${cell(md(row.expected))} | ☐ | |`),
    "",
    `## ${t("testcase.final")}`,
    "",
    ...task.result.map((item) => `- ${escapeMarkdown(item)}`),
    "",
    `## ${t("testcase.signoff")}`,
    "",
    `| ${t("testcase.tester")} | ${t("testcase.date")} | ${t("testcase.outcome")} |`,
    "| --- | --- | --- |",
    "| | | ☐ |",
    ""
  );
  lines.push(...sourceDetails(task));
  return lines.join("\n");
}

function taskLink(task) {
  return `[${escapeMarkdown(task.title)}](./${task.id}.md)`;
}

export function renderUseCase(useCase, catalog, { processImage, bpmnFile } = {}) {
  const { language } = catalog;
  const lines = [
    "<!-- Generated by BC Atlas docs. Do not edit this file. -->",
    "",
    `# ${label(language, "label.use-case")}: ${escapeMarkdown(useCase.title)}`,
    ""
  ];
  if (processImage) {
    lines.push(`## ${label(language, "heading.process")}`, "", `![${escapeMarkdown(useCase.title)}](./${processImage})`, "");
    if (bpmnFile) lines.push(label(language, "label.bpmn", { file: `[${bpmnFile}](./${bpmnFile})` }), "");
  }
  lines.push(`## ${label(language, "heading.main-scenario")}`, "");
  for (const [index, task] of useCase.main.entries()) {
    lines.push(`${index + 1}. ${taskLink(task)}${sameAsTitle(task) ? "" : ` - ${escapeMarkdown(task.goal)}`}`);
  }
  lines.push("");
  if (useCase.alternatives.length) {
    lines.push(`## ${label(language, "heading.alternatives")}`, "",
      ...useCase.alternatives.map((task) => `- ${taskLink(task)}${sameAsTitle(task) ? "" : ` - ${escapeMarkdown(task.goal)}`}`), "");
  }
  return lines.join("\n");
}

/**
 * One business process across several scenarios: what it is, who does what,
 * and every stage with its steps, in the order the scenarios link.
 */
export function renderJourney(journey, catalog, { processImage } = {}) {
  const { language } = catalog;
  const t = (key, values) => label(language, key, values);
  const lines = [
    "<!-- Generated by BC Atlas docs. Do not edit this file. -->",
    "",
    `# ${t("label.journey")}: ${escapeMarkdown(journey.title)}`,
    ""
  ];
  if (processImage) lines.push(`## ${t("heading.process")}`, "", `![${escapeMarkdown(journey.title)}](./${processImage})`, "");
  lines.push(`## ${t("heading.stages")}`, "");
  for (const [index, task] of journey.tasks.entries()) {
    const who = [...task.roles, ...task.permissions];
    lines.push(`${index + 1}. ${taskLink(task)}${who.length ? ` (${escapeMarkdown(who.join(", "))})` : ""}`);
  }
  lines.push("");
  for (const [index, task] of journey.tasks.entries()) {
    lines.push(`## ${index + 1}. ${escapeMarkdown(task.title)}`, "");
    if (!sameAsTitle(task)) lines.push(escapeMarkdown(task.goal), "");
    lines.push(...performedBy(task));
    const prereqs = task.prereqs.filter(({ kind }) => kind !== "requires");
    if (prereqs.length) {
      lines.push(`### ${t("heading.prereq")}`, "", ...prereqs.map((item) => `- ${mdTokens(prereqLine(item, language))}`), "");
    }
    if (task.steps.length) {
      lines.push(`### ${t("heading.steps")}`, "");
      for (const [number, step] of task.steps.entries()) lines.push(`${number + 1}. ${withInfo(step)}`, ...stepLines(step, 3));
      lines.push("");
    }
    lines.push(`### ${t("heading.result")}`, "", ...task.result.map((item) => `- ${escapeMarkdown(item)}`), "");
    lines.push(guideLine(task, language), "");
  }
  return lines.join("\n").replace(/\n{3,}/gu, "\n\n");
}

function guideLine(task, language) {
  return mdTokens(phrase(language, "label.guide", { guide: { raw: taskLink(task) } }));
}

/** What support needs, scenario by scenario: [MONITOR], [RECOVERY], [TROUBLESHOOT]. */
export function renderRunbook(catalog) {
  const { language } = catalog;
  const lines = [
    "<!-- Generated by BC Atlas docs. Do not edit this file. -->",
    "",
    `# ${label(language, "heading.runbook")}${catalog.title ? `: ${escapeMarkdown(catalog.title)}` : ""}`,
    ""
  ];
  for (const task of catalog.runbook) {
    lines.push(`## ${escapeMarkdown(task.title)}`, "", guideLine(task, language), "",
      ...runbookLines(task, 3));
  }
  return lines.join("\n").replace(/\n{3,}/gu, "\n\n");
}

function indexTable(heading, column, rows, t) {
  if (!rows.length) return [];
  return [`## ${t(heading)}`, "", `| ${t(column)} | ${t("column.scenarios")} |`, "| --- | --- |",
    ...rows.map(({ name, tasks }) => `| ${textCell(name)} | ${tasks.map(taskLink).join(", ")} |`), ""];
}

/** Catalog landing page: use cases, journeys, scenarios, journey graph, indexes, runbook, coverage. */
export function renderIndex(catalog, { journeyImage } = {}) {
  const { language } = catalog;
  const t = (key, values) => label(language, key, values);
  const lines = [
    "<!-- Generated by BC Atlas docs. Do not edit this file. -->",
    "",
    `# ${escapeMarkdown(catalog.title ?? t("heading.documentation"))}`,
    ""
  ];
  const named = catalog.useCases.filter(({ feature }) => feature);
  if (named.length) {
    lines.push(`## ${t("heading.use-cases")}`, "");
    for (const useCase of catalog.useCases) {
      const count = useCase.main.length + useCase.alternatives.length;
      lines.push(`- [${escapeMarkdown(useCase.title)}](./${useCase.id}.md) (${count})`);
    }
    lines.push("");
  }
  if (catalog.journeys.length) {
    lines.push(`## ${t("heading.journeys")}`, "",
      ...catalog.journeys.map((journey) => `- [${escapeMarkdown(journey.title)}](./${journey.id}.md) (${journey.tasks.length})`), "");
  }
  lines.push(`## ${t("heading.scenarios")}`, "", ...catalog.tasks.map((task) => `- ${taskLink(task)}`), "");
  if (journeyImage) lines.push(`## ${t("heading.journey")}`, "", `![${t("heading.journey")}](./${journeyImage})`, "");
  lines.push(
    ...indexTable("heading.by-feature", "column.feature", catalog.byFeature, t),
    ...indexTable("heading.by-role", "column.role", catalog.byRole, t),
    ...indexTable("heading.by-page", "column.page", catalog.byPage, t),
    ...indexTable("heading.by-permission", "column.permission-set", catalog.byPermission, t)
  );
  if (catalog.runbook.length) {
    lines.push(`## ${t("heading.runbook")}`, "", `- [${t("heading.runbook")}](./runbook.md) (${catalog.runbook.length})`, "");
  }
  const { coverage } = catalog;
  if (coverage.total !== undefined || coverage.undocumentedTests.length) {
    lines.push(`## ${t("heading.coverage")}`, "");
    if (coverage.total !== undefined) lines.push(t("label.coverage", { covered: String(coverage.covered), total: String(coverage.total) }), "");
    if (coverage.undocumentedTests.length) {
      lines.push(`### ${t("heading.undocumented-tests")}`, "", t("label.undocumented", { count: String(coverage.undocumentedTests.length) }), "",
        ...coverage.undocumentedTests.map(({ file, procedure }) => `- \`${file}#${procedure}\``), "");
    }
    if (coverage.untouchedPages?.length) {
      lines.push(`### ${t("heading.untouched-pages")}`, "",
        ...coverage.untouchedPages.map(({ caption, id }) => `- ${escapeMarkdown(caption)}${id ? ` (${id})` : ""}`), "");
    }
    if (coverage.unusedActions?.length) {
      lines.push(`### ${t("heading.unused-actions")}`, "",
        ...coverage.unusedActions.map(({ page, action }) => `- ${escapeMarkdown(page)}: ${escapeMarkdown(action)}`), "");
    }
  }
  return lines.join("\n");
}

