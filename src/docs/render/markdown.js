import { label, phrase } from "../phrases.js";
import { inlineStep } from "../steps.js";
import { humanizeFeature, sameAsTitle } from "../task.js";
import { escapeMarkdown, markdown as md } from "./format.js";

const LINK_HEADINGS = { next: "heading.next", related: "heading.related", alternative: "heading.alternative" };

function link(target, extension = ".md") {
  return target.exists ? `[${escapeMarkdown(target.title)}](./${target.id}${extension})` : `**${escapeMarkdown(target.id)}**`;
}

function cell(value) {
  return String(value ?? "").replaceAll("|", "\\|").replace(/\r?\n/gu, " ");
}

function header(task) {
  return [
    `<!-- Generated by BC Atlas docs from ${task.source.file}#${task.source.procedure}. Do not edit this file. -->`,
    `<!-- Source SHA-256: ${task.source.hash} -->`,
    ""
  ];
}

function sourceDetails(task) {
  const { language } = task;
  return [
    "<details>",
    `<summary>${label(language, "heading.source")}</summary>`,
    "",
    `- ${label(language, "label.file")}: \`${task.source.file}\``,
    `- ${label(language, "label.function")}: \`${task.source.procedure}\``,
    `- ${label(language, "label.hash")}: \`${task.source.hash}\``,
    "",
    "</details>",
    ""
  ];
}

function prereqLine(item, language) {
  if (item.kind === "requires") return phrase(language, "label.requires", { guide: { raw: link(item.link) } });
  return item.tokens;
}

function mdTokens(tokens) {
  return tokens.map((token) => (token?.raw !== undefined ? token.raw : md([token]))).join("");
}

function withInfo(step) {
  return `${md(step.cmd)}${step.info ? ` _${escapeMarkdown(step.info)}_` : ""}`;
}

function stepLines(step, indent) {
  const pad = " ".repeat(indent);
  const lines = [];
  for (const item of step.items ?? []) {
    lines.push(`${pad}- ${withInfo(item)}`);
    for (const nested of item.items ?? []) lines.push(`${pad}  - ${withInfo(nested)}`);
  }
  return lines;
}

function flowSection(task, flowImage) {
  if (!flowImage) return [];
  const heading = label(task.language, "heading.flow");
  return [`## ${heading}`, "", `![${escapeMarkdown(task.title)}](./${flowImage})`, ""];
}

/** User guide in the shape of a DITA task: prerequisites, steps, result, links. */
export function renderGuide(task, { flowImage } = {}) {
  const { language } = task;
  const lines = [...header(task), `# ${task.title}`, "", md(task.shortdesc), "", ...flowSection(task, flowImage)];
  if (task.prereqs.length) {
    lines.push(`## ${label(language, "heading.prereq")}`, "",
      ...task.prereqs.map((item) => `- ${mdTokens(prereqLine(item, language))}`), "");
  }
  if (task.steps.length) {
    lines.push(`## ${label(language, "heading.steps")}`, "");
    if (task.examples) lines.push(`> ${label(language, "label.examples")}`, "");
    for (const [index, step] of task.steps.entries()) {
      lines.push(`${index + 1}. ${withInfo(step)}`, ...stepLines(step, 3));
      if (step.result?.length) {
        lines.push("", `   ${md(phrase(language, "label.step-result", { result: step.result.join(" ") }))}`, "");
      }
    }
    lines.push("");
  }
  lines.push(`## ${label(language, "heading.result")}`, "", ...task.result.map((item) => `- ${item}`), "");
  for (const [kind, heading] of Object.entries(LINK_HEADINGS)) {
    if (task.links[kind].length) {
      lines.push(`## ${label(language, heading)}`, "", ...task.links[kind].map((target) => `- ${link(target)}`), "");
    }
  }
  lines.push(...sourceDetails(task));
  return lines.join("\n").replace(/\n{3,}/gu, "\n\n");
}

/**
 * Flattens a task into numbered test-case rows: { action, expected }.
 * Preconditions become the first row so the table works on its own.
 */
export function testCaseRows(task) {
  const { language } = task;
  const rows = [];
  if (task.prereqs.length) {
    rows.push({
      action: phrase(language, "testcase.check-preconditions"),
      expected: phrase(language, "testcase.preconditions-met")
    });
  }
  for (const step of task.steps) {
    if (step.items?.length) {
      for (const item of step.items) {
        rows.push({
          action: item.items?.length ? inlineStep(item, language) : item.cmd,
          expected: item.expected ?? []
        });
      }
      const last = rows.at(-1);
      if (step.result?.length || step.expected?.length) last.expected = step.result?.length ? [step.result.join(" ")] : step.expected;
    } else {
      rows.push({ action: step.cmd, expected: step.expected ?? [] });
    }
  }
  if (rows.length && task.result.length) rows.at(-1).expected = [task.result.join(" ")];
  return rows;
}

/** Test-case specification with an executable step table and sign-off block. */
export function renderTestCase(task, { flowImage } = {}) {
  const { language } = task;
  const t = (key, values) => label(language, key, values);
  const lines = [...header(task), `# ${t("testcase.title", { id: task.id })}: ${task.title}`, ""];
  lines.push(
    "| | |",
    "| --- | --- |",
    `| ${t("testcase.id")} | \`${task.id}\` |`,
    `| ${t("testcase.objective")} | ${cell(task.goal)} |`
  );
  if (task.features.length) lines.push(`| ${t("label.use-case")} | ${cell(task.features.map(humanizeFeature).join(", "))} |`);
  if (task.permissions.length) lines.push(`| ${t("testcase.permissions")} | ${cell(task.permissions.join(", "))} |`);
  lines.push(`| ${t("testcase.source")} | \`${task.source.file}#${task.source.procedure}\` |`, "");
  lines.push(...flowSection(task, flowImage));

  const preconditions = task.prereqs.filter(({ kind }) => kind !== "permission");
  if (preconditions.length) {
    lines.push(`## ${t("testcase.preconditions")}`, "",
      ...preconditions.map((item) => `- ${mdTokens(prereqLine(item, language))}`), "");
  }
  lines.push(
    `## ${t("testcase.steps")}`,
    "",
    `| ${t("testcase.step")} | ${t("testcase.action")} | ${t("testcase.expected")} | ${t("testcase.pass")} | ${t("testcase.actual")} |`,
    "| ---: | --- | --- | :---: | --- |",
    ...testCaseRows(task).map((row, index) =>
      `| ${index + 1} | ${cell(md(row.action))} | ${cell(md(row.expected))} | ☐ | |`),
    "",
    `## ${t("testcase.final")}`,
    "",
    ...task.result.map((item) => `- ${item}`),
    "",
    `## ${t("testcase.signoff")}`,
    "",
    `| ${t("testcase.tester")} | ${t("testcase.date")} | ${t("testcase.outcome")} |`,
    "| --- | --- | --- |",
    "| | | ☐ |",
    ""
  );
  lines.push(...sourceDetails(task));
  return lines.join("\n");
}

function taskLink(task) {
  return `[${escapeMarkdown(task.title)}](./${task.id}.md)`;
}

export function renderUseCase(useCase, catalog, { processImage, bpmnFile } = {}) {
  const { language } = catalog;
  const lines = [
    "<!-- Generated by BC Atlas docs. Do not edit this file. -->",
    "",
    `# ${label(language, "label.use-case")}: ${escapeMarkdown(useCase.title)}`,
    ""
  ];
  if (processImage) {
    lines.push(`## ${label(language, "heading.process")}`, "", `![${escapeMarkdown(useCase.title)}](./${processImage})`, "");
    if (bpmnFile) lines.push(label(language, "label.bpmn", { file: `[${bpmnFile}](./${bpmnFile})` }), "");
  }
  lines.push(`## ${label(language, "heading.main-scenario")}`, "");
  for (const [index, task] of useCase.main.entries()) {
    lines.push(`${index + 1}. ${taskLink(task)}${sameAsTitle(task) ? "" : ` - ${escapeMarkdown(task.goal)}`}`);
  }
  lines.push("");
  if (useCase.alternatives.length) {
    lines.push(`## ${label(language, "heading.alternatives")}`, "",
      ...useCase.alternatives.map((task) => `- ${taskLink(task)}${sameAsTitle(task) ? "" : ` - ${escapeMarkdown(task.goal)}`}`), "");
  }
  return lines.join("\n");
}

/** Catalog landing page: use cases, scenarios, journey, indexes, coverage. */
export function renderIndex(catalog, { journeyImage } = {}) {
  const { language } = catalog;
  const t = (key, values) => label(language, key, values);
  const lines = [
    "<!-- Generated by BC Atlas docs. Do not edit this file. -->",
    "",
    `# ${escapeMarkdown(catalog.title ?? t("heading.documentation"))}`,
    ""
  ];
  const named = catalog.useCases.filter(({ feature }) => feature);
  if (named.length) {
    lines.push(`## ${t("heading.use-cases")}`, "");
    for (const useCase of catalog.useCases) {
      const count = useCase.main.length + useCase.alternatives.length;
      lines.push(`- [${escapeMarkdown(useCase.title)}](./${useCase.id}.md) (${count})`);
    }
    lines.push("");
  }
  lines.push(`## ${t("heading.scenarios")}`, "", ...catalog.tasks.map((task) => `- ${taskLink(task)}`), "");
  if (journeyImage) lines.push(`## ${t("heading.journey")}`, "", `![${t("heading.journey")}](./${journeyImage})`, "");
  if (catalog.byPage.length) {
    lines.push(`## ${t("heading.by-page")}`, "", `| ${t("column.page")} | ${t("column.scenarios")} |`, "| --- | --- |",
      ...catalog.byPage.map(({ name, tasks }) => `| ${cell(name)} | ${tasks.map(taskLink).join(", ")} |`), "");
  }
  if (catalog.byPermission.length) {
    lines.push(`## ${t("heading.by-permission")}`, "", `| ${t("column.permission-set")} | ${t("column.scenarios")} |`, "| --- | --- |",
      ...catalog.byPermission.map(({ name, tasks }) => `| ${cell(name)} | ${tasks.map(taskLink).join(", ")} |`), "");
  }
  if (catalog.coverage) {
    const { coverage } = catalog;
    lines.push(`## ${t("heading.coverage")}`, "", t("label.coverage", { covered: String(coverage.covered), total: String(coverage.total) }), "");
    if (coverage.untouchedPages.length) {
      lines.push(`### ${t("heading.untouched-pages")}`, "",
        ...coverage.untouchedPages.map(({ caption, id }) => `- ${escapeMarkdown(caption)}${id ? ` (${id})` : ""}`), "");
    }
    if (coverage.unusedActions.length) {
      lines.push(`### ${t("heading.unused-actions")}`, "",
        ...coverage.unusedActions.map(({ page, action }) => `- ${escapeMarkdown(page)}: ${escapeMarkdown(action)}`), "");
    }
  }
  return lines.join("\n");
}

