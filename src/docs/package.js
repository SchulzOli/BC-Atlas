import fs from "node:fs/promises";
import path from "node:path";
import { strToU8, zipSync } from "fflate";

import { renderDocumentation } from "./markdown.js";
import { loadCorpus } from "./model.js";

const GENERATED_MARKER = "Generated by BC Atlas docs package";
const APP_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/iu;
const PROCEDURE_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/u;

function portablePath(filename) {
  return filename.replaceAll("\\", "/");
}

function yamlScalar(value) {
  return JSON.stringify(String(value));
}

function unique(values) {
  return [...new Set(values)];
}

async function owningApp(filename) {
  let directory = path.dirname(filename);
  while (true) {
    const manifest = path.join(directory, "app.json");
    try {
      const value = JSON.parse(await fs.readFile(manifest, "utf8"));
      if (!value.id || !value.version) {
        throw new Error(`${manifest} must define id and version`);
      }
      return {
        id: String(value.id),
        version: String(value.version),
        name: value.name ? String(value.name) : undefined,
        root: directory,
        manifest
      };
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    const parent = path.dirname(directory);
    if (parent === directory) break;
    directory = parent;
  }
  throw new Error(`No owning app.json found for ${filename}`);
}

function inputBase(root) {
  return path.extname(root).toLowerCase() === ".al" ? path.dirname(root) : root;
}

function validatePackageScenarios(scenarios) {
  const ids = new Map();
  const filenames = new Map();
  const messages = [];
  for (const scenario of scenarios) {
    const { id, filename } = scenario.value;
    const existingId = ids.get(id);
    if (existingId) {
      messages.push(`Duplicate calculated document ID "${id}" for ` +
        `${existingId.relativePath}#${existingId.value.procedure} and ` +
        `${scenario.relativePath}#${scenario.value.procedure}`);
    } else {
      ids.set(id, scenario);
    }
    const filenameKey = filename.toLocaleLowerCase("en-US");
    const existingFilename = filenames.get(filenameKey);
    if (existingFilename) {
      messages.push(`Duplicate guide filename "${filename}" for ` +
        `${existingFilename.relativePath}#${existingFilename.value.procedure} and ` +
        `${scenario.relativePath}#${scenario.value.procedure}`);
    } else {
      filenames.set(filenameKey, scenario);
    }
  }
  if (messages.length) throw new Error(messages.join("\n"));
}

function resolveReferences(scenarios) {
  const byId = new Map(scenarios.map((scenario) => [scenario.value.id, scenario]));
  const localProcedures = new Map();
  const legacyIds = new Map();
  for (const scenario of scenarios) {
    const appId = scenario.value.app.id;
    localProcedures.set(
      `${appId}\0${scenario.value.procedure.toLocaleLowerCase("en-US")}`,
      scenario
    );
    legacyIds.set(
      `${appId}\0${scenario.value.legacyId.toLocaleLowerCase("en-US")}`,
      scenario
    );
  }
  const resolve = (source, target) =>
    byId.get(target) ??
    localProcedures.get(`${source.value.app.id}\0${target.toLocaleLowerCase("en-US")}`) ??
    legacyIds.get(`${source.value.app.id}\0${target.toLocaleLowerCase("en-US")}`);

  for (const scenario of scenarios) {
    const links = {};
    for (const [relation, targets] of Object.entries(scenario.value.links)) {
      const rawTargets = relation === "requires"
        ? unique([...targets, ...(scenario.value.xmlRequires ?? [])])
        : targets;
      links[relation] = unique(rawTargets.map((target) =>
        resolve(scenario, target)?.value.id ?? target
      ));
    }
    scenario.value.links = links;
  }
  for (const scenario of scenarios) {
    for (const target of scenario.value.links.requires ?? []) {
      const required = byId.get(target);
      if (required) required.value.links.next = unique([
        ...(required.value.links.next ?? []),
        scenario.value.id
      ]);
    }
  }
  return byId;
}

function packageDiagnostic(scenario, code, message) {
  return {
    severity: "error",
    code,
    message,
    file: scenario.relativePath,
    procedure: scenario.value.procedure,
    documentId: scenario.value.id
  };
}

export function guidePolicyDiagnostics(scenarios) {
  const diagnostics = [];
  const titles = new Map();
  for (const scenario of scenarios) {
    for (const field of ["role", "process", "stage"]) {
      if (!scenario.value[field]) {
        diagnostics.push({
          ...packageDiagnostic(
            scenario,
            `missing-${field}`,
            `Guide "${scenario.value.title}" has no ${field} classification`
          ),
          severity: "warning"
        });
      }
    }
    const titleKey = scenario.value.title.toLocaleLowerCase("en-US");
    const existing = titles.get(titleKey);
    if (existing) {
      diagnostics.push({
        ...packageDiagnostic(
          scenario,
          "duplicate-guide-title",
          `Guide title "${scenario.value.title}" is also used by ` +
          `${existing.relativePath}#${existing.value.procedure}`
        ),
        severity: "warning"
      });
    } else {
      titles.set(titleKey, scenario);
    }
  }
  return diagnostics;
}

function packageLinkDiagnostics(scenarios, byId) {
  const diagnostics = [];
  for (const scenario of scenarios) {
    if (!APP_ID_PATTERN.test(scenario.value.app.id) ||
        !PROCEDURE_PATTERN.test(scenario.value.procedure)) {
      diagnostics.push(packageDiagnostic(
        scenario,
        "invalid-calculated-document-id",
        `Cannot calculate a document ID from app ID "${scenario.value.app.id}" and ` +
        `procedure "${scenario.value.procedure}"`
      ));
    }
    for (const [relation, targets] of Object.entries(scenario.value.links)) {
      for (const target of targets) {
        if (target === scenario.value.id) {
          diagnostics.push(packageDiagnostic(
            scenario,
            "self-document-link",
            `Document "${target}" cannot link to itself as ${relation}`
          ));
        } else if (!byId.has(target)) {
          diagnostics.push(packageDiagnostic(
            scenario,
            "broken-document-link",
            `${relation} target "${target}" does not exist`
          ));
        }
      }
    }
  }

  const state = new Map();
  const stack = [];
  const visit = (scenario) => {
    const id = scenario.value.id;
    if (state.get(id) === "done") return;
    if (state.get(id) === "visiting") {
      const start = stack.indexOf(id);
      diagnostics.push(packageDiagnostic(
        scenario,
        "requires-cycle",
        `Hard prerequisite cycle: ${[...stack.slice(start), id].join(" -> ")}`
      ));
      return;
    }
    state.set(id, "visiting");
    stack.push(id);
    for (const target of scenario.value.links.requires ?? []) {
      const required = byId.get(target);
      if (required) visit(required);
    }
    stack.pop();
    state.set(id, "done");
  };
  for (const scenario of scenarios) visit(scenario);
  return diagnostics;
}

async function packageCorpus(input) {
  const corpus = await loadCorpus(input);
  const base = inputBase(corpus.root);
  const scenarios = [];
  for (const source of corpus.scenarios) {
    const app = await owningApp(source.path);
    const sourceFile = portablePath(path.relative(base, source.path));
    const procedure = source.value.procedure;
    scenarios.push({
      ...source,
      value: {
        ...source.value,
        legacyId: source.value.id,
        id: `${app.id}-${procedure}`,
        idSource: "calculated",
        filename: `${procedure}.md`,
        app,
        sourceFile,
        sourceSha256: source.fileHash
      }
    });
  }
  scenarios.sort((left, right) =>
    left.value.id.localeCompare(right.value.id) || left.reference.localeCompare(right.reference)
  );
  validatePackageScenarios(scenarios);
  const byId = resolveReferences(scenarios);
  const diagnostics = [
    ...corpus.diagnostics.filter(({ code }) => ![
      "invalid-link-target",
      "broken-document-link",
      "self-document-link",
      "requires-cycle"
    ].includes(code)),
    ...guidePolicyDiagnostics(scenarios),
    ...packageLinkDiagnostics(scenarios, byId)
  ];
  return {
    ...corpus,
    scenarios,
    byId,
    diagnostics
  };
}

function appendOptionalMetadata(lines, value, indentation) {
  for (const key of ["role", "process", "stage", "owner", "type"]) {
    if (value[key]) lines.push(`${indentation}${key}: ${yamlScalar(value[key])}`);
  }
  for (const relation of ["requires", "next"]) {
    const targets = value.links?.[relation] ?? [];
    if (!targets.length) continue;
    lines.push(`${indentation}${relation}:`);
    for (const target of targets) lines.push(`${indentation}  - ${yamlScalar(target)}`);
  }
}

function metadataLines(value) {
  const lines = [
    `    documentId: ${yamlScalar(value.id)}`,
    `    appId: ${yamlScalar(value.app.id)}`,
    `    filename: ${yamlScalar(value.filename)}`,
    `    title: ${yamlScalar(value.title)}`,
    `    sourceFile: ${yamlScalar(value.sourceFile)}`,
    `    procedure: ${yamlScalar(value.procedure)}`,
    `    sourceSha256: ${yamlScalar(value.sourceSha256)}`
  ];
  appendOptionalMetadata(lines, value, "    ");
  return lines;
}

export function renderPackageMetadata(corpus, options = {}) {
  const apps = new Map(corpus.scenarios.map(({ value }) => [value.app.id, value.app]));
  const lines = [
    "schemaVersion: 1",
    "apps:"
  ];
  for (const app of [...apps.values()].sort((left, right) => left.id.localeCompare(right.id))) {
    lines.push(`  ${app.id}:`, `    version: ${yamlScalar(app.version)}`);
    if (options.commit) lines.push(`    commit: ${yamlScalar(options.commit)}`);
  }
  lines.push("guides:");
  for (const scenario of corpus.scenarios) {
    lines.push("  -", ...metadataLines(scenario.value));
  }
  return `${lines.join("\n")}\n`;
}

function renderFrontmatter(value) {
  const lines = [
    "---",
    `documentId: ${yamlScalar(value.id)}`,
    `appId: ${yamlScalar(value.app.id)}`,
    `sourceFile: ${yamlScalar(value.sourceFile)}`,
    `procedure: ${yamlScalar(value.procedure)}`,
    `sourceSha256: ${yamlScalar(value.sourceSha256)}`
  ];
  appendOptionalMetadata(lines, value, "");
  lines.push("---", "");
  return lines.join("\n");
}

function guideLink(scenario) {
  return `[${scenario.value.title}](./${scenario.value.filename})`;
}

function renderNavigation(scenario, corpus) {
  const back = (scenario.value.links.requires ?? [])
    .map((id) => corpus.byId.get(id))
    .filter(Boolean);
  const next = (scenario.value.links.next ?? [])
    .map((id) => corpus.byId.get(id))
    .filter(Boolean);
  const parts = [];
  if (back.length) parts.push(`Back: ${back.map(guideLink).join(", ")}`);
  parts.push("[Index](./index.md)");
  if (next.length) parts.push(`Next: ${next.map(guideLink).join(", ")}`);
  return `${parts.join(" | ")}\n\n`;
}

function matrixLines(corpus) {
  const classified = corpus.scenarios.filter(({ value }) => value.process && value.role);
  if (!classified.length) return [];
  const roles = unique(classified.map(({ value }) => value.role)).sort();
  const processes = unique(classified.map(({ value }) => value.process)).sort();
  const lines = [
    "## Process by role",
    "",
    `| Process | ${roles.join(" | ")} |`,
    `| --- | ${roles.map(() => "---").join(" | ")} |`
  ];
  for (const process of processes) {
    const cells = roles.map((role) => classified
      .filter(({ value }) => value.process === process && value.role === role)
      .sort((left, right) => left.value.title.localeCompare(right.value.title))
      .map(guideLink)
      .join("<br>"));
    lines.push(`| ${process} | ${cells.join(" | ")} |`);
  }
  return [...lines, ""];
}

function orderedJourney(scenarios) {
  const members = new Map(scenarios.map((scenario) => [scenario.value.id, scenario]));
  const remaining = new Map(scenarios.map((scenario) => [
    scenario.value.id,
    (scenario.value.links.requires ?? []).filter((id) => members.has(id)).length
  ]));
  const ordered = [];
  while (ordered.length < scenarios.length) {
    const ready = scenarios
      .filter((scenario) => !ordered.includes(scenario) && remaining.get(scenario.value.id) === 0)
      .sort((left, right) => left.value.title.localeCompare(right.value.title));
    if (!ready.length) return [...scenarios].sort((left, right) => left.value.title.localeCompare(right.value.title));
    const current = ready[0];
    ordered.push(current);
    for (const candidate of scenarios) {
      if ((candidate.value.links.requires ?? []).includes(current.value.id)) {
        remaining.set(candidate.value.id, remaining.get(candidate.value.id) - 1);
      }
    }
  }
  return ordered;
}

function journeyLines(corpus) {
  const processes = unique(corpus.scenarios.map(({ value }) => value.process).filter(Boolean)).sort();
  if (!processes.length) return [];
  const lines = ["## Process journeys", ""];
  for (const process of processes) {
    const journey = orderedJourney(corpus.scenarios.filter(({ value }) => value.process === process));
    lines.push(`### ${process}`, "", journey.map(guideLink).join(" → "), "");
  }
  return lines;
}

async function generatedFiles(directory) {
  let entries;
  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return [];
    throw error;
  }
  const files = [];
  for (const entry of entries) {
    if (!entry.isFile()) continue;
    const filename = path.join(directory, entry.name);
    const content = await fs.readFile(filename, "utf8").catch(() => "");
    if (content.includes(GENERATED_MARKER)) files.push(entry.name);
  }
  return files.sort();
}

async function packageDifferences(output, files) {
  const differences = [];
  for (const [relative, expected] of files) {
    const current = await fs.readFile(path.join(output, relative), "utf8").catch((error) => {
      if (error.code === "ENOENT") return undefined;
      throw error;
    });
    if (current === undefined) differences.push(`missing ${relative}`);
    else if (current !== expected) differences.push(`changed ${relative}`);
  }
  for (const relative of await generatedFiles(output)) {
    if (!files.has(relative)) differences.push(`stale ${relative}`);
  }
  return differences;
}

async function writePackageAtomically(output, files) {
  const parent = path.dirname(output);
  const temporary = path.join(parent, `.${path.basename(output)}.tmp-${process.pid}`);
  const backup = path.join(parent, `.${path.basename(output)}.bak-${process.pid}`);
  await fs.mkdir(parent, { recursive: true });
  await fs.rm(temporary, { recursive: true, force: true });
  await fs.rm(backup, { recursive: true, force: true });
  try {
    await fs.cp(output, temporary, { recursive: true });
  } catch (error) {
    if (error.code === "ENOENT") await fs.mkdir(temporary, { recursive: true });
    else throw error;
  }
  try {
    for (const relative of await generatedFiles(temporary)) {
      if (!files.has(relative)) await fs.rm(path.join(temporary, relative), { force: true });
    }
    for (const [relative, content] of files) {
      const filename = path.join(temporary, relative);
      await fs.mkdir(path.dirname(filename), { recursive: true });
      await fs.writeFile(filename, content, "utf8");
    }
    let hadOutput = false;
    try {
      await fs.rename(output, backup);
      hadOutput = true;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    try {
      await fs.rename(temporary, output);
    } catch (error) {
      if (hadOutput) await fs.rename(backup, output);
      throw error;
    }
    await fs.rm(backup, { recursive: true, force: true });
  } catch (error) {
    await fs.rm(temporary, { recursive: true, force: true });
    throw error;
  }
}

function assertPackageDiagnostics(corpus, strict) {
  const serious = corpus.diagnostics.filter(({ severity }) =>
    severity === "error" || (strict && severity === "warning")
  );
  if (serious.length) {
    throw new Error(serious.map(({ severity, code, message }) =>
      `${severity}: ${code}: ${message}`
    ).join("\n"));
  }
}

async function writeFileAtomically(filename, content) {
  const output = path.resolve(filename);
  const temporary = `${output}.tmp-${process.pid}`;
  const backup = `${output}.bak-${process.pid}`;
  await fs.mkdir(path.dirname(output), { recursive: true });
  await fs.rm(temporary, { force: true });
  await fs.rm(backup, { force: true });
  await fs.writeFile(temporary, content, typeof content === "string" ? "utf8" : undefined);
  let hadOutput = false;
  try {
    await fs.rename(output, backup);
    hadOutput = true;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  try {
    await fs.rename(temporary, output);
    await fs.rm(backup, { force: true });
  } catch (error) {
    await fs.rm(temporary, { force: true });
    if (hadOutput) await fs.rename(backup, output);
    throw error;
  }
  return output;
}

function renderPackageZip(files) {
  const entries = {};
  const mtime = new Date(Date.UTC(1980, 0, 1));
  for (const [filename, content] of [...files.entries()].sort(([left], [right]) =>
    left.localeCompare(right)
  )) {
    entries[filename] = [strToU8(content), { mtime, os: 3, attrs: 0o644 << 16 }];
  }
  return zipSync(entries, { level: 9, mtime, os: 3 });
}

function renderIndex(corpus) {
  const guides = [...corpus.scenarios].sort((left, right) =>
    left.value.title.localeCompare(right.value.title) || left.value.id.localeCompare(right.value.id)
  );
  return [
    `<!-- ${GENERATED_MARKER}. Do not edit this file. -->`,
    "",
    "# User guides",
    "",
    ...guides.map(({ value }) => `- [${value.title}](./${value.filename})`),
    "",
    ...matrixLines(corpus),
    ...journeyLines(corpus)
  ].join("\n");
}

export async function createDocumentationPackage(input, options = {}) {
  const corpus = await packageCorpus(input);
  const files = new Map([
    ["metadata.yml", renderPackageMetadata(corpus, options)],
    ["index.md", renderIndex(corpus)]
  ]);
  for (const scenario of corpus.scenarios) {
    files.set(
      scenario.value.filename,
      `${renderFrontmatter(scenario.value)}<!-- ${GENERATED_MARKER}. Do not edit this file. -->\n\n` +
      renderNavigation(scenario, corpus) +
      renderDocumentation(scenario, { catalog: corpus.byId, sourceVerification: false })
    );
  }
  return { corpus, files };
}

export async function writeDocumentationMetadata(input, outputFile, options = {}) {
  if (!outputFile) throw new Error("--output is required for docs metadata");
  const packageData = await createDocumentationPackage(input, options);
  assertPackageDiagnostics(packageData.corpus, options.strict);
  const output = await writeFileAtomically(outputFile, packageData.files.get("metadata.yml"));
  return { output, corpus: packageData.corpus };
}

export async function writeDocumentationPackage(input, outputDirectory, options = {}) {
  const output = path.resolve(outputDirectory ?? "Docu/UI");
  const packageData = await createDocumentationPackage(input, options);
  assertPackageDiagnostics(packageData.corpus, options.strict);
  const archive = options.zip ? renderPackageZip(packageData.files) : undefined;
  if (options.check) {
    const differences = await packageDifferences(output, packageData.files);
    if (options.zip) {
      const currentArchive = await fs.readFile(path.resolve(options.zip)).catch((error) => {
        if (error.code === "ENOENT") return undefined;
        throw error;
      });
      if (!currentArchive) differences.push(`missing ${options.zip}`);
      else if (!currentArchive.equals(Buffer.from(archive))) differences.push(`changed ${options.zip}`);
    }
    if (differences.length) {
      throw new Error(`documentation package is stale:\n${differences.join("\n")}`);
    }
  } else {
    await writePackageAtomically(output, packageData.files);
    if (options.zip) await writeFileAtomically(options.zip, archive);
  }
  return {
    outputDirectory: output,
    files: [...packageData.files.keys()],
    corpus: packageData.corpus,
    checked: Boolean(options.check),
    zip: options.zip ? path.resolve(options.zip) : undefined
  };
}

