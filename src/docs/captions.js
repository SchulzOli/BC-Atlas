// Resolves the captions and tooltips a user actually sees for the pages,
// fields, and actions that a UI test touches. Captions come from the app's AL
// source; translations come from the app's XLIFF files. Nothing is invented:
// when a caption is unknown, callers fall back to the humanized control name.
import fs from "node:fs/promises";
import path from "node:path";
import { analyze } from "../analyzer.js";

const key = (...parts) => parts.map((part) => String(part ?? "").trim().toLowerCase()).join("\u0000");

function unquote(value) {
  return String(value ?? "").trim().replace(/^"(.*)"$/u, "$1");
}

/** Reads the first AL string literal of a property value such as 'Caption', Comment = '...'. */
export function alString(value) {
  const match = /^'((?:[^']|'')*)'/u.exec(String(value ?? "").trim());
  return match ? match[1].replaceAll("''", "'") : undefined;
}

function property(properties, name) {
  return alString(properties?.find((item) => item.name?.toLowerCase() === name.toLowerCase())?.value);
}

/** Removes AL access-key markers: "&Post" -> "Post", "R&&D" -> "R&D", "A & B" stays. */
function withoutAccessKey(value) {
  return value === undefined ? undefined : value.replace(/&(&|(?=[^\s&]))/gu, (_, double) => double);
}

function decodeXml(value) {
  return value
    .replace(/<[^>]+>/gu, "")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&quot;", "\"")
    .replaceAll("&apos;", "'")
    .replaceAll("&amp;", "&")
    .trim();
}

/**
 * Parses the XLIFF generated by the AL compiler. The "Xliff Generator" note
 * names the element, e.g. "Page Customer Card - Control Name - Property Caption".
 */
export function parseXliff(content) {
  const language = /target-language="([^"]+)"/u.exec(content)?.[1];
  const entries = new Map();
  for (const unit of content.matchAll(/<trans-unit\b[\s\S]*?<\/trans-unit>/gu)) {
    const target = /<target\b[^>]*>([\s\S]*?)<\/target>/u.exec(unit[0])?.[1];
    const note = /<note\b[^>]*from="Xliff Generator"[^>]*>([\s\S]*?)<\/note>/u.exec(unit[0])?.[1];
    if (target === undefined || !note) continue;
    const text = decodeXml(target);
    if (!text) continue;
    entries.set(xliffKey(decodeXml(note)), text);
  }
  return { language, entries };
}

const XLIFF_ELEMENT = /^(Page|PageExtension|Table|TableExtension|Control|Action|Field|Property)\s+(.+)$/u;

function xliffKey(note) {
  const segments = note.split(" - ").map((segment) => XLIFF_ELEMENT.exec(segment.trim())).filter(Boolean);
  return key(...segments.flatMap(([, type, name]) => [type, name]));
}

async function xliffFiles(directory, depth = 0) {
  if (depth > 4) return [];
  const entries = await fs.readdir(directory, { withFileTypes: true }).catch(() => []);
  const files = [];
  for (const entry of entries) {
    if (entry.isDirectory() && ![".git", "node_modules", ".alpackages"].includes(entry.name)) {
      files.push(...await xliffFiles(path.join(directory, entry.name), depth + 1));
    } else if (entry.isFile() && entry.name.toLowerCase().endsWith(".xlf")) {
      files.push(path.join(directory, entry.name));
    }
  }
  return files.sort();
}

async function loadTranslation(appRoot, language) {
  if (!language) return undefined;
  const wanted = language.toLowerCase();
  const base = wanted.split(/[-_]/u)[0];
  let fallback;
  for (const file of await xliffFiles(appRoot)) {
    const parsed = parseXliff(await fs.readFile(file, "utf8"));
    const target = parsed.language?.toLowerCase();
    if (!target) continue;
    if (target === wanted) return { ...parsed, file };
    if (!fallback && target.split(/[-_]/u)[0] === base) fallback = { ...parsed, file };
  }
  return fallback;
}

function pageRecord() {
  return { caption: undefined, controls: new Map(), actions: new Map(), parts: new Map(), sourceTable: undefined };
}

/**
 * Builds a caption index for an AL app.
 * @returns {{ language?: string, translationFile?: string, pages: Map, page(name), control(page, path), action(page, path) }}
 */
export async function loadCaptionIndex(appRoot, { language } = {}) {
  const model = await analyze(appRoot);
  const translation = await loadTranslation(path.resolve(appRoot), language);
  const translate = (fallback, ...parts) => withoutAccessKey(translation?.entries.get(key(...parts)) ?? fallback);

  const tables = new Map();
  for (const object of model.objects.filter(({ type, externalSymbol }) => !externalSymbol && ["table", "tableextension"].includes(type))) {
    const tableName = object.type === "table"
      ? object.name
      : unquote(object.relations?.find(({ kind }) => kind === "extends")?.target ?? object.name);
    const fields = tables.get(key(tableName)) ?? new Map();
    for (const field of object.fields ?? []) {
      const objectType = object.type === "table" ? "Table" : "TableExtension";
      const caption = translate(property(field.properties, "Caption"), objectType, object.name, "Field", field.name, "Property", "Caption");
      fields.set(key(field.name), {
        caption: caption ?? field.name,
        tooltip: translate(property(field.properties, "ToolTip"), objectType, object.name, "Field", field.name, "Property", "ToolTip")
      });
    }
    tables.set(key(tableName), fields);
  }

  const pages = new Map();
  const pageObjects = model.objects.filter(({ type, externalSymbol }) => !externalSymbol && ["page", "pageextension"].includes(type));
  // Base pages first so extensions add to an existing record.
  pageObjects.sort((left, right) => (left.type === "page" ? 0 : 1) - (right.type === "page" ? 0 : 1));
  for (const object of pageObjects) {
    const isPage = object.type === "page";
    const objectType = isPage ? "Page" : "PageExtension";
    const pageName = isPage ? object.name : unquote(object.relations?.find(({ kind }) => kind === "extends")?.target ?? "");
    if (!pageName) continue;
    const record = pages.get(key(pageName)) ?? pageRecord();
    pages.set(key(pageName), record);
    if (isPage) {
      record.name = object.name;
      record.id = object.id;
      record.caption = translate(property(object.properties, "Caption") ?? object.name, "Page", object.name, "Property", "Caption");
      record.sourceTable = unquote(object.properties?.find(({ name }) => name === "SourceTable")?.value ?? "");
      record.file = object.file;
    }
    for (const field of object.fields ?? []) {
      const column = /^Rec\.(.+)$/u.exec(field.sourceExpression ?? "")?.[1];
      const tableField = column ? tables.get(key(record.sourceTable))?.get(key(unquote(column))) : undefined;
      const own = property(field.properties, "Caption");
      record.controls.set(key(field.name), {
        name: field.name,
        caption: translate(own, objectType, object.name, "Control", field.name, "Property", "Caption") ??
          tableField?.caption ?? (column ? unquote(column) : undefined),
        tooltip: translate(property(field.properties, "ToolTip"), objectType, object.name, "Control", field.name, "Property", "ToolTip") ??
          tableField?.tooltip
      });
    }
    for (const part of object.parts ?? []) {
      record.parts.set(key(part.name), {
        name: part.name,
        page: unquote(part.target),
        caption: translate(property(part.properties, "Caption"), objectType, object.name, "Control", part.name, "Property", "Caption")
      });
    }
    for (const action of object.actions ?? []) {
      if (action.kind === "action-ref") continue;
      record.actions.set(key(action.name), {
        name: action.name,
        caption: translate(property(action.properties, "Caption"), objectType, object.name, "Action", action.name, "Property", "Caption"),
        tooltip: translate(property(action.properties, "ToolTip"), objectType, object.name, "Action", action.name, "Property", "ToolTip")
      });
    }
  }

  const findPage = (name) => pages.get(key(unquote(name)));

  /** Walks part controls (e.g. Lines.Quantity) to the page that owns the member. */
  function owner(pageName, sections) {
    let page = findPage(pageName);
    const sectionCaptions = [];
    for (const section of sections) {
      const part = page?.parts.get(key(section));
      sectionCaptions.push(part?.caption ?? findPage(part?.page)?.caption);
      page = part ? findPage(part.page) : undefined;
    }
    return { page, sectionCaptions };
  }

  return {
    appName: model.apps.find(({ root }) => path.resolve(root ?? "") === path.resolve(appRoot))?.name ?? model.apps[0]?.name,
    language: translation?.language,
    translationFile: translation?.file,
    pages,
    page: (name) => findPage(name),
    member(pageName, sections, member, kind) {
      const { page, sectionCaptions } = owner(pageName, sections);
      const collection = kind === "action" ? page?.actions : page?.controls;
      return { ...(collection?.get(key(member)) ?? {}), sectionCaptions };
    }
  };
}
