import fs from "node:fs/promises";
import path from "node:path";
import { generatedDocumentationPath } from "./al-ui-source.js";

function bullets(items) {
  return items.map((item) => `- ${item}`).join("\n");
}

const PREREQUISITE_LABELS = {
  setup: "Setup",
  "master-data": "Master data",
  environment: "Environment",
  "feature-flag": "Feature flag",
  state: "Required state"
};

const LINK_SECTIONS = [
  ["next", "Next steps"],
  ["related", "Related guides"],
  ["alternative", "Alternative paths"]
];

function linkedGuide(target, catalog) {
  const scenario = catalog?.get(target);
  return scenario ? `[${scenario.value.title}](./${target}.md)` : `**${target}**`;
}

export function renderDocumentation(source, options = {}) {
  const { value } = source;
  const procedure = value.guideSteps.length ? value.guideSteps : value.actions;
  const sourceFile = path.basename(source.path);
  const prerequisites = value.typedPrerequisites?.length
    ? value.typedPrerequisites.map(({ type, text }) =>
        type === "general" ? text : `${PREREQUISITE_LABELS[type]}: ${text}`
      )
    : value.guidePrerequisites;
  const beforeYouStart = [
    ...value.permissions.map((permission) => `Required permission: **${permission}**`),
    ...prerequisites,
    ...(value.links?.requires ?? []).map((target) =>
      `Complete ${linkedGuide(target, options.catalog)} first.`
    )
  ];
  const lines = [
    `<!-- Generated by BC Atlas docs from ${sourceFile}#${value.procedure}. Do not edit this file. -->`,
    `<!-- Source SHA-256: ${value.sourceHash} -->`,
    "",
    `# ${value.title}`,
    "",
    `Use this guide to ${value.guideGoal.replace(/^[A-Z]/u, (letter) => letter.toLowerCase()).replace(/\.$/u, "")}.`,
    ""
  ];

  if (beforeYouStart.length) {
    lines.push("## Before you start", "", bullets(beforeYouStart), "");
  }
  if (procedure.length) {
    lines.push("## Steps", "");
    if (value.hasExampleValues) {
      lines.push(
        "> The values below are examples from the automated UI test. Use values appropriate for your environment.",
        ""
      );
    }
    if (value.guideSections?.length) {
      for (const [index, section] of value.guideSections.entries()) {
        lines.push(`${index + 1}. ${section.title}`);
        for (const step of section.steps) lines.push(`   - ${step}`);
      }
      lines.push("");
    } else {
      lines.push(
        ...procedure.map((action, index) => `${index + 1}. ${action}`),
        ""
      );
    }
  }
  lines.push(
    "## What should happen",
    "",
    bullets(value.guideExpected),
    ""
  );
  for (const [relation, title] of LINK_SECTIONS) {
    const targets = value.links?.[relation] ?? [];
    if (targets.length) {
      lines.push(`## ${title}`, "", bullets(
        targets.map((target) => linkedGuide(target, options.catalog))
      ), "");
    }
  }
  lines.push(
    "<details>",
    "<summary>Source and verification</summary>",
    "",
    `- File: \`${sourceFile}\``,
    `- Function: \`${value.procedure}\``,
    `- Source SHA-256: \`${value.sourceHash}\``,
    "",
    "</details>",
    ""
  );
  return lines.join("\n");
}

export async function writeDocumentation(source, outputDirectory, options = {}) {
  const filename = generatedDocumentationPath(
    source.value,
    outputDirectory ?? process.env.BC_DOCS_OUTPUT ?? "docs/generated"
  );
  await fs.mkdir(path.dirname(filename), { recursive: true });
  await fs.writeFile(filename, renderDocumentation(source, options));
  return filename;
}

export async function writeCorpusDocumentation(corpus, outputDirectory) {
  if (corpus.diagnostics.some(({ severity }) => severity === "error")) {
    throw new Error("documentation corpus has errors; run docs validate for details");
  }
  const written = [];
  for (const scenario of corpus.scenarios) {
    written.push(await writeDocumentation(scenario, outputDirectory, {
      catalog: corpus.byId
    }));
  }
  const directory = path.resolve(outputDirectory ?? process.env.BC_DOCS_OUTPUT ?? "docs/generated");
  const index = path.join(directory, "index.md");
  const lines = [
    "<!-- Generated by BC Atlas docs. Do not edit this file. -->",
    "",
    "# Documentation",
    "",
    ...corpus.scenarios.map(({ value }) => `- [${value.title}](./${value.id}.md)`),
    ""
  ];
  await fs.mkdir(directory, { recursive: true });
  await fs.writeFile(index, lines.join("\n"));
  written.push(index);
  return written;
}
