import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";
import { validateScenario } from "./scenario.js";

function safeName(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/gu, "-").replace(/^-|-$/gu, "") || "image";
}

function bullets(items) {
  return items.map((item) => `- ${item}`).join("\n");
}

function procedureSteps(steps) {
  const visible = [];
  const visit = (step) => {
    if (step.category === "test.step") visible.push(step.title);
    for (const child of step.steps ?? []) visit(child);
  };
  for (const step of steps) visit(step);
  return visible;
}

function scenarioAnnotation(test) {
  return test.annotations.find(({ type }) => type === "scenario")?.description;
}

export default class MarkdownDocumentationReporter {
  constructor(options = {}) {
    this.outputDir = path.resolve(options.outputDir ?? process.env.BC_DOCS_OUTPUT ?? "docs/generated");
  }

  onTestEnd(test, result) {
    if (result.status !== "passed") return;
    const scenarioFile = scenarioAnnotation(test);
    if (!scenarioFile) return;

    const scenarioPath = path.resolve(scenarioFile);
    const scenario = validateScenario(
      YAML.parse(fs.readFileSync(scenarioPath, "utf8")),
      path.basename(scenarioPath)
    );
    const steps = procedureSteps(result.steps);
    const verificationPrefix = "Verify: ";
    const verified = new Set(
      steps.filter((step) => step.startsWith(verificationPrefix))
        .map((step) => step.slice(verificationPrefix.length))
    );
    const missing = scenario.expected.filter((expected) => !verified.has(expected));
    if (missing.length) {
      throw new Error(`${test.title} does not verify: ${missing.join("; ")}`);
    }
    const procedure = steps.filter((step) => !step.startsWith(verificationPrefix));
    if (!procedure.length) throw new Error(`${test.title} has no customer-visible procedure steps`);

    const imageDir = path.join(this.outputDir, "images");
    fs.mkdirSync(imageDir, { recursive: true });
    const images = [];
    for (const attachment of result.attachments.filter(({ contentType }) =>
      contentType?.startsWith("image/")
    )) {
      const extension = attachment.contentType === "image/jpeg" ? "jpg" : "png";
      const filename = `${scenario.id}-${safeName(attachment.name)}.${extension}`;
      const destination = path.join(imageDir, filename);
      if (attachment.body) fs.writeFileSync(destination, attachment.body);
      else if (attachment.path) fs.copyFileSync(attachment.path, destination);
      images.push({ name: attachment.name, filename });
    }

    const lines = [
      "<!-- Generated by ald2tree docs. Edit the scenario or executable test, not this file. -->",
      "",
      `# ${scenario.title}`,
      "",
      scenario.description || scenario.goal,
      ""
    ];
    if (scenario.prerequisites.length) {
      lines.push("## Prerequisites", "", bullets(scenario.prerequisites), "");
    }
    lines.push(
      "## Procedure",
      "",
      ...procedure.map((step, index) => `${index + 1}. ${step}`),
      "",
      "## Expected result",
      "",
      bullets(scenario.expected),
      "",
      `Verified automatically on ${new Date().toISOString().slice(0, 10)}.`
    );
    for (const image of images) {
      lines.push("", `![${image.name}](images/${image.filename})`);
    }
    lines.push("");

    fs.mkdirSync(this.outputDir, { recursive: true });
    fs.writeFileSync(path.join(this.outputDir, `${scenario.id}.md`), lines.join("\n"));
  }
}
