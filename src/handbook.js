// The system handbook: Markdown pages that explain an AL system as a whole,
// generated from the analyzed source. Where the object catalog
// (codegraph.js) has one page per object, the handbook answers questions
// across all of them:
//
//   README.md        what the system consists of: apps, components, object
//                    types, the objects everything else relies on
//   events.md        which events exist, who raises them, who reacts
//   data.md          which tables exist, who reads and writes them, how
//   permissions.md   which permission sets grant what, and what nothing grants
//   interfaces.md    contracts, their implementations, and enum bindings
//   ui.md            what users can open: pages and reports by usage
//                    category, APIs, and the source tables behind them
//   code-health.md   complexity, size, obsolete code, documentation coverage
//
// `bca export --view handbook` writes it; `bca run` has a handbook task.
import fs from "node:fs/promises";
import path from "node:path";
import { assessArchitecture } from "./blueprint/index.js";
import { catalogLayout } from "./codegraph.js";

const MARKER = "<!-- Generated by BC Atlas (handbook). Do not edit; run bca export --view handbook. -->";

const TYPE_LABELS = {
  table: "Table", tableextension: "Table extension", page: "Page", pageextension: "Page extension", pagecustomization: "Page customization",
  codeunit: "Codeunit", report: "Report", reportextension: "Report extension", query: "Query", xmlport: "XMLport", enum: "Enum",
  enumextension: "Enum extension", interface: "Interface", controladdin: "Control add-in", profile: "Profile", profileextension: "Profile extension",
  permissionset: "Permission set", permissionsetextension: "Permission set extension", entitlement: "Entitlement"
};

const cell = (value) => value === undefined || value === null || value === "" ? "" : String(value).replaceAll("|", "\\|").replace(/\r?\n/gu, " ");
const table = (headers, rows) => rows.length ? [
  `| ${headers.join(" | ")} |`,
  `| ${headers.map((header) => header.startsWith(">") ? "---:" : "---").join(" | ")} |`,
  ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ""
].map((line) => line.replaceAll("| >", "| ")) : [];
const plural = (count, one, many = `${one}s`) => `${count.toLocaleString("en-US")} ${count === 1 ? one : many}`;
const label = (object) => object ? `${TYPE_LABELS[object.type] ?? object.type} ${object.id ? `${object.id} ` : ""}${object.name}` : "";
const byName = (a, b) => String(a.name).localeCompare(String(b.name), "en", { numeric: true }) || String(a.type).localeCompare(String(b.type));

/** Insert, modify, delete, or read, from the operation of a data relation. */
function crud(edge) {
  if (edge.kind === "reads") return "R";
  const operation = String(edge.operation ?? "").toLowerCase();
  if (operation.startsWith("insert")) return "I";
  if (operation.startsWith("delete")) return "D";
  if (["modify", "modifyall", "rename", "validate", "setrange"].some((name) => operation.startsWith(name)) || edge.kind === "writes") return "M";
  return "R";
}

function header(title, intro) {
  return [MARKER, "", `# ${title}`, "", ...(intro ? [intro, ""] : [])];
}

function overviewPage(context) {
  const { workspace, model, assessment, pages } = context;
  const counts = new Map();
  for (const object of workspace) counts.set(object.type, (counts.get(object.type) ?? 0) + 1);
  const lines = header(context.title, "What this system consists of and how it hangs together, generated from its AL source. Each page below answers one question across all objects.");
  lines.push("## Contents", "", ...pages.filter(({ file }) => file !== "README.md").map(({ file, title, summary }) => `- [${title}](${context.pageLink(file)}): ${summary}`), "");

  lines.push("## Apps", "", ...table(["App", "Publisher", "Version", ">Objects"], (model.apps ?? []).map((app) => [
    app.name, app.publisher, app.version, workspace.filter((object) => object.app?.id === app.id).length
  ])));

  lines.push("## Object types", "", ...table(["Type", ">Objects"], [...counts].sort((a, b) => b[1] - a[1]).map(([type, count]) => [TYPE_LABELS[type] ?? type, count])));

  const components = assessment?.result.components ?? [];
  if (components.length) {
    const configured = Boolean(assessment.context.options.architecture?.components?.length);
    const described = new Map((assessment.architecture?.components ?? []).map((component) => [component.name, component.description]));
    lines.push("## Components", "",
      configured
        ? "The components of the architecture in `.bca.json`; layer 0 is the core, and dependencies may only point to lower layers."
        : "No architecture is configured yet; these components are what `bca architecture --propose` derives from today's dependencies.", "",
      ...table(["Layer", "Component", ">Objects", "Depends on", "Purpose"], [...components]
        .sort((a, b) => (a.layer ?? 0) - (b.layer ?? 0) || a.name.localeCompare(b.name))
        .map((component) => [component.layer, component.name, component.metrics.objects, (component.dependsOn ?? component.dependsOnActual ?? []).join(", "), described.get(component.name)])));
  }

  // The objects most others rely on: changes to them reach furthest.
  const usedBy = new Map();
  for (const edge of model.edges) {
    if (!edge.to || edge.from === edge.to || ["permits", "includes"].includes(edge.kind) || !context.isWorkspace(edge.to)) continue;
    if (!usedBy.has(edge.to)) usedBy.set(edge.to, new Set());
    usedBy.get(edge.to).add(edge.from);
  }
  const central = [...usedBy].map(([key, users]) => ({ object: context.objectOf(key), users: users.size }))
    .filter(({ object }) => object).sort((a, b) => b.users - a.users || byName(a.object, b.object)).slice(0, 15);
  if (central.length) {
    lines.push("## Objects everything relies on", "", "Used by the most other objects; a change to them reaches furthest.", "",
      ...table(["Object", ">Used by", "Purpose"], central.map(({ object, users }) => [context.link(object), users, object.metadata?.documentation ?? object.metadata?.caption])));
  }
  return lines;
}

function eventsPage(context) {
  const { workspace, model } = context;
  const lines = header("Events", "Events are how objects react to each other without depending on each other directly. For every event: who raises it and who reacts to it.");
  const subscriptions = model.edges.filter(({ kind }) => kind === "subscribes");
  const subscribersOf = new Map();
  for (const edge of subscriptions) {
    const key = `${edge.to ?? `unresolved:${edge.unresolved?.name}`}\u0000${String(edge.event ?? "").toLowerCase()}`;
    if (!subscribersOf.has(key)) subscribersOf.set(key, []);
    subscribersOf.get(key).push(edge);
  }
  const published = workspace.flatMap((object) => (object.procedures ?? [])
    .filter(({ kind }) => kind === "event")
    .map((procedure) => ({ object, procedure, subscribers: subscribersOf.get(`${object.key}\u0000${procedure.name.toLowerCase()}`) ?? [] })));
  lines.push(`${plural(published.length, "event")} published here, ${plural(subscriptions.length, "subscription")}.`, "");

  const kindOf = (procedure) => /BusinessEvent/iu.test((procedure.attributes ?? []).join(" ")) ? "business" : /InternalEvent/iu.test((procedure.attributes ?? []).join(" ")) ? "internal" : "integration";
  if (published.length) {
    const unused = published.filter(({ subscribers }) => !subscribers.length).length;
    lines.push("## Events published in this system", "",
      unused ? `${plural(unused, "event")} without a subscriber here: extension points for other apps, or events no longer needed.` : "Every event has a subscriber here.", "",
      ...table(["Publisher", "Event", "Kind", "Description", "Subscribers"], published
        .sort((a, b) => byName(a.object, b.object) || a.procedure.name.localeCompare(b.procedure.name))
        .map(({ object, procedure, subscribers }) => [
          context.link(object),
          `\`${procedure.name}\``,
          kindOf(procedure),
          procedure.metadata?.documentation,
          subscribers.map((edge) => `${context.link(context.objectOf(edge.from))} (\`${edge.member}\`)`).join("; ") || "none"
        ])));
  }
  const external = subscriptions.filter((edge) => !context.isWorkspace(edge.to));
  if (external.length) {
    lines.push("## Events of other apps this system reacts to", "", "Subscriptions to events of dependencies such as the Base Application: where this system hooks into standard processes.", "",
      ...table(["Publisher", "Event", "Subscriber"], external
        .map((edge) => [context.objectOf(edge.to) ? context.link(context.objectOf(edge.to)) : edge.unresolved?.name, edge.event ? `\`${edge.event}\`` : "", `${context.link(context.objectOf(edge.from))} (\`${edge.member}\`)`])
        .sort((a, b) => String(a[0]).localeCompare(String(b[0])) || String(a[1]).localeCompare(String(b[1])))));
  }
  return lines;
}

function dataPage(context) {
  const { workspace, model } = context;
  const lines = header("Data", "Which tables this system has, who reads and writes them, and how. I = insert, M = modify, D = delete, R = read.");
  const tables = workspace.filter(({ type }) => type === "table").sort(byName);
  const access = new Map();
  for (const edge of model.edges) {
    if (!["reads", "writes"].includes(edge.kind) || !edge.to || edge.from === edge.to) continue;
    if (!access.has(edge.to)) access.set(edge.to, new Map());
    const users = access.get(edge.to);
    if (!users.has(edge.from)) users.set(edge.from, new Set());
    users.get(edge.from).add(crud(edge));
  }
  const sourced = new Map();
  for (const object of workspace) {
    const source = object.metadata?.sourceTable;
    if (source) sourced.set(source.toLowerCase(), [...(sourced.get(source.toLowerCase()) ?? []), object]);
  }
  const extensions = new Map();
  for (const edge of model.edges.filter((edge) => edge.kind === "extends" && context.objectOf(edge.from)?.type === "tableextension")) {
    extensions.set(edge.to, [...(extensions.get(edge.to) ?? []), context.objectOf(edge.from)]);
  }
  const letters = (set) => ["I", "M", "D", "R"].filter((letter) => set.has(letter)).join("");
  lines.push("## Tables", "", ...table(["Table", "Caption", "Classification", ">Fields", "Written by", "Read by", "Shown on"], tables.map((object) => {
    const users = [...(access.get(object.key) ?? [])].map(([key, set]) => ({ object: context.objectOf(key), set })).filter(({ object }) => object);
    const writers = users.filter(({ set }) => [...set].some((letter) => letter !== "R"));
    const readers = users.filter(({ set }) => ![...set].some((letter) => letter !== "R"));
    return [
      context.link(object),
      object.metadata?.caption,
      object.metadata?.dataClassification,
      object.metadata?.size?.fields ?? 0,
      writers.map(({ object: user, set }) => `${user.name} (${letters(set)})`).join(", ") || "nobody",
      readers.map(({ object: user }) => user.name).join(", "),
      (sourced.get(String(object.name).toLowerCase()) ?? []).map((user) => user.name).join(", ")
    ];
  })));

  // Tables of other apps (Base Application) this system writes to.
  const foreign = [...access].filter(([key]) => !context.isWorkspace(key) && context.objectOf(key)?.type === "table")
    .map(([key, users]) => ({ object: context.objectOf(key), users: [...users].filter(([, set]) => [...set].some((letter) => letter !== "R")) }))
    .filter(({ users }) => users.length).sort((a, b) => byName(a.object, b.object));
  if (foreign.length) {
    lines.push("## Tables of other apps this system writes", "", "Data owned by a dependency that this system changes directly.", "",
      ...table(["Table", "Written by"], foreign.map(({ object, users }) => [context.link(object), users.map(([key, set]) => `${context.objectOf(key)?.name} (${letters(set)})`).join(", ")])));
  }
  const extended = [...extensions].map(([key, list]) => [context.objectOf(key), list]).filter(([object]) => object);
  if (extended.length) {
    lines.push("## Table extensions", "", ...table(["Extends", "Extension", ">Fields added"], extended.flatMap(([base, list]) => list.map((extension) => [context.link(base), context.link(extension), extension.metadata?.size?.fields ?? 0]))));
  }
  const unwritten = tables.filter((object) => ![...(access.get(object.key)?.values() ?? [])].some((set) => [...set].some((letter) => letter !== "R")));
  if (unwritten.length && tables.length) {
    lines.push("## Tables no code here writes", "", "Filled through pages, configuration packages, APIs, or other apps; or no longer used.", "",
      ...unwritten.map((object) => `- ${context.link(object)}${sourced.has(String(object.name).toLowerCase()) ? " (edited on a page)" : ""}`), "");
  }
  return lines;
}

function permissionsPage(context) {
  const { workspace, model } = context;
  const lines = header("Permissions", "What each permission set grants, and the tables and objects no permission set covers.");
  const sets = workspace.filter(({ type }) => ["permissionset", "permissionsetextension"].includes(type)).sort(byName);
  const grants = model.edges.filter(({ kind }) => kind === "permits");
  const includes = model.edges.filter(({ kind }) => kind === "includes");
  if (!sets.length) return [...lines, "This system defines no permission sets.", ""];
  for (const set of sets) {
    const own = grants.filter(({ from }) => from === set.key);
    const included = includes.filter(({ from }) => from === set.key).map((edge) => context.objectOf(edge.to)?.name ?? edge.unresolved?.name);
    lines.push(`## ${label(set)}`, "",
      [set.metadata?.caption && `Caption: ${set.metadata.caption}.`, set.assignable === false ? "Not assignable (only included in others)." : set.assignable ? "Assignable to users." : "", included.length ? `Includes ${included.join(", ")}.` : ""].filter(Boolean).join(" ") || "", "",
      ...table(["Object", "Kind", "Rights"], own.map((edge) => [
        context.objectOf(edge.to) ? context.link(context.objectOf(edge.to)) : edge.unresolved?.name,
        edge.permissionKind ?? "object",
        edge.permissionKind === "tabledata" ? (edge.access ?? "") : edge.execute ? "X" : edge.access ?? ""
      ]).sort((a, b) => String(a[0]).localeCompare(String(b[0])))));
  }
  const covered = new Set(grants.filter(({ permissionKind }) => permissionKind === "tabledata").map(({ to }) => to));
  const uncovered = workspace.filter(({ type, key }) => type === "table" && !covered.has(key) && !/^\s*(temporary)\s*$/iu.test(context.objectOf(key)?.metadata?.tableType ?? "")).sort(byName);
  if (uncovered.length) {
    lines.push("## Tables without table data permissions", "", "No permission set of this system grants access to their data; users need permissions from elsewhere.", "",
      ...uncovered.map((object) => `- ${context.link(object)}`), "");
  }
  return lines;
}

function interfacesPage(context) {
  const { workspace, model } = context;
  const lines = header("Interfaces", "Contracts that let one object call another without knowing which implementation runs, and the enum values that choose an implementation.");
  const interfaces = model.objects.filter(({ type }) => type === "interface")
    .filter((object) => context.isWorkspace(object.key) || model.edges.some(({ kind, to, from }) => kind === "implements" && to === object.key && context.isWorkspace(from)))
    .sort(byName);
  if (!interfaces.length) return [...lines, "This system defines or implements no interfaces.", ""];
  for (const contract of interfaces) {
    const implementations = model.edges.filter(({ kind, to }) => kind === "implements" && to === contract.key).map(({ from }) => context.objectOf(from)).filter(Boolean).sort(byName);
    const bindings = model.edges.filter(({ kind, contract: name }) => kind === "selects" && String(name ?? "").toLowerCase() === String(contract.name).toLowerCase());
    lines.push(`## ${context.link(contract)}${context.isWorkspace(contract.key) ? "" : " (from another app)"}`, "",
      ...(contract.metadata?.documentation ? [contract.metadata.documentation, ""] : []),
      ...((contract.procedures ?? []).length ? ["Methods: " + contract.procedures.map(({ name }) => `\`${name}\``).join(", "), ""] : []),
      ...table(["Implementation", "Selected by"], implementations.map((implementation) => [
        context.link(implementation),
        bindings.filter(({ to }) => to === implementation.key).map((edge) => `${context.objectOf(edge.from)?.name}::${edge.member}`).join(", ")
      ])),
      ...(implementations.length ? [] : ["No implementation in this system.", ""]));
  }
  return lines;
}

function uiPage(context) {
  const { workspace } = context;
  const lines = header("User interface", "What users can open, grouped the way Business Central offers it (usage category), with the data behind each page.");
  const pages = workspace.filter(({ type }) => type === "page");
  const reports = workspace.filter(({ type }) => type === "report");
  const api = pages.filter(({ metadata }) => /^api$/iu.test(metadata?.pageType ?? ""));
  const searchable = [...pages, ...reports].filter(({ metadata }) => metadata?.usageCategory && !/^none$/iu.test(metadata.usageCategory));
  const categories = new Map();
  for (const object of searchable) categories.set(object.metadata.usageCategory, [...(categories.get(object.metadata.usageCategory) ?? []), object]);
  lines.push(`${plural(pages.length, "page")} (${plural(searchable.filter(({ type }) => type === "page").length, "page")} found by search), ${plural(reports.length, "report")}, ${plural(api.length, "API page")}.`, "");
  for (const [category, list] of [...categories].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`## ${category}`, "", ...table(["Object", "Caption", "Type", "Source table", "Application area"], list.sort(byName).map((object) => [
      context.link(object), object.metadata.caption, object.metadata.pageType ?? (object.type === "report" ? "Report" : ""), object.metadata.sourceTable, object.metadata.applicationArea?.join(", ")
    ])));
  }
  const others = pages.filter((object) => !searchable.includes(object) && !api.includes(object)).sort(byName);
  if (others.length) {
    lines.push("## Opened from other pages", "", "Cards, subpages, and dialogs that search does not list.", "",
      ...table(["Page", "Caption", "Type", "Source table"], others.map((object) => [context.link(object), object.metadata?.caption, object.metadata?.pageType, object.metadata?.sourceTable])));
  }
  if (api.length) {
    lines.push("## APIs", "", ...table(["Page", "Endpoint", "Source table"], api.sort(byName).map((object) => [
      context.link(object), [object.metadata.apiPublisher, object.metadata.apiGroup, object.metadata.apiVersion, object.metadata.entityName].filter(Boolean).join("/"), object.metadata.sourceTable
    ])));
  }
  return lines;
}

function healthPage(context) {
  const { workspace } = context;
  const lines = header("Code health", "Where the code is hard to change: complex procedures, large objects, obsolete code, and what is not documented.");
  const procedures = workspace.flatMap((object) => (object.procedures ?? []).filter(({ hasBody }) => hasBody).map((procedure) => ({ object, procedure })));
  const complex = procedures.filter(({ procedure }) => (procedure.metadata?.complexity ?? 0) > 1)
    .sort((a, b) => b.procedure.metadata.complexity - a.procedure.metadata.complexity || (b.procedure.metadata.lines ?? 0) - (a.procedure.metadata.lines ?? 0)).slice(0, 25);
  const total = procedures.reduce((sum, { procedure }) => sum + (procedure.metadata?.complexity ?? 0), 0);
  lines.push(`${plural(procedures.length, "procedure")} and triggers with code; cyclomatic complexity ${total.toLocaleString("en-US")} in all. Complexity counts the paths through a procedure: 1, plus 1 for each \`if\`, loop, \`case\` branch, and \`and\` or \`or\`. Above 10, a procedure is hard to test; above 20, hard to change safely.`, "");
  if (complex.length) {
    lines.push("## Most complex procedures", "", ...table(["Procedure", "Object", ">Complexity", ">Lines"], complex.map(({ object, procedure }) => [
      `\`${procedure.name}\``, context.link(object), procedure.metadata.complexity, procedure.metadata.lines
    ])));
  }
  const large = [...workspace].filter(({ metadata }) => metadata?.size?.lines).sort((a, b) => b.metadata.size.lines - a.metadata.size.lines).slice(0, 15);
  if (large.length) {
    lines.push("## Largest objects", "", ...table(["Object", ">Lines", ">Procedures", ">Complexity"], large.map((object) => [
      context.link(object), object.metadata.size.lines, object.metadata.size.procedures ?? 0, object.metadata.complexity?.total ?? ""
    ])));
  }
  const obsolete = [
    ...workspace.filter(({ metadata }) => metadata?.obsolete).map((object) => [context.link(object), object.metadata.obsolete]),
    ...workspace.flatMap((object) => (object.procedures ?? []).filter(({ metadata }) => metadata?.obsolete).map((procedure) => [`\`${procedure.name}\` in ${context.link(object)}`, procedure.metadata.obsolete])),
    ...workspace.flatMap((object) => (object.fields ?? []).filter(({ metadata }) => metadata?.obsolete).map((field) => [`Field ${field.name} in ${context.link(object)}`, field.metadata.obsolete]))
  ];
  if (obsolete.length) {
    lines.push("## Obsolete", "", "Marked for removal; plan the work before the tag's version.", "",
      ...table(["What", "State", "Tag", "Reason"], obsolete.map(([what, info]) => [what, info.state, info.tag, info.reason])));
  }
  const publicProcedures = workspace.filter(({ type }) => ["codeunit", "table", "page", "report", "query", "xmlport", "interface"].includes(type))
    .flatMap((object) => (object.procedures ?? []).filter(({ kind, visibility }) => kind === "procedure" && (visibility ?? "public") === "public").map((procedure) => ({ object, procedure })));
  const documented = publicProcedures.filter(({ procedure }) => procedure.metadata?.documentation).length;
  const undocumentedObjects = workspace.filter(({ type, metadata }) => ["codeunit", "interface"].includes(type) && !metadata?.documentation);
  lines.push("## Documentation coverage", "",
    `${documented.toLocaleString("en-US")} of ${plural(publicProcedures.length, "public procedure")} have a \`///\` summary${publicProcedures.length ? ` (${Math.round((documented / publicProcedures.length) * 100)}%)` : ""}.`, "");
  if (undocumentedObjects.length) {
    lines.push("Codeunits and interfaces without a `///` summary:", "", ...undocumentedObjects.sort(byName).slice(0, 50).map((object) => `- ${context.link(object)}`),
      ...(undocumentedObjects.length > 50 ? [`- and ${undocumentedObjects.length - 50} more`] : []), "");
  }
  return lines;
}

