async function assertReplaceable(directory) {
  let entries;
  try {
    entries = await fs.readdir(directory);
  } catch (error) {
    if (error.code === "ENOENT") return;
    throw error;
  }
  if (!entries.length) return;
  const readme = await fs.readFile(path.join(directory, "README.md"), "utf8").catch(() => "");
  if (!readme.startsWith(MARKER)) {
    throw new Error(`${directory} is not empty and was not written by bca export --view handbook; choose another --output`);
  }
}

/**
 * The handbook pages as Markdown, without writing them.
 * @param values.linkTo object => link target of its page, or undefined
 * @param values.pageLink file => link to another handbook page (default ./file)
 * @param context.assessment an assessArchitecture result to reuse (the app's)
 * @param context.model an analyzed project (analyzeProject) to reuse
 * @returns { pages: [{ file, title, content }], objects }
 */
export async function renderHandbook(input, values = {}, { assessment: given, model: analyzed } = {}) {
  // A model analyzed already (for the catalog's layout) is reused, unless
  // --paths selects files, which the assessment then analyzes on its own.
  const assessment = given ?? await assessArchitecture(input, values, analyzed && !values.paths?.length ? { model: analyzed } : {});
  const model = assessment.model;
  const workspace = model.objects.filter(({ externalSymbol }) => !externalSymbol);
  const keys = new Set(workspace.map(({ key }) => key));
  const objects = new Map(model.objects.map((object) => [object.key, object]));
  const apps = (model.apps ?? []).map(({ name }) => name).filter(Boolean);
  // English, or German with a de language tag (values.language).
  const t = handbookText(values.language);
  const label = (object) => object ? `${t.types[object.type] ?? object.type} ${object.id ? `${object.id} ` : ""}${object.name}` : "";
  const context = {
    model,
    workspace,
    assessment,
    pages: PAGES,
    t,
    label,
    title: values.title ?? t.defaultTitle(apps.length === 1 ? apps[0] : path.basename(path.resolve(input))),
    isWorkspace: (key) => keys.has(key),
    objectOf: (key) => objects.get(key),
    pageLink: values.pageLink ?? ((file) => `./${file}`),
    // An object's label (or just its name), linked where values.linkTo knows a page for it.
    link: (object, text = label(object)) => {
      const target = object && values.linkTo?.(object);
      return target ? `[${String(text).replaceAll("[", "\\[").replaceAll("]", "\\]")}](${target})` : text;
    },
    name: (object) => context.link(object, object?.name ?? "")
  };
  const pages = PAGES.map((page) => ({
    file: page.file,
    title: page.file === "README.md" ? context.title : t.pages[page.file].title,
    summary: t.pages[page.file].summary,
    content: `${page.render(context).join("\n").replace(/\n{3,}/gu, "\n\n").trim()}\n`
  }));
  return { pages, objects: workspace.length };
}

const encodeLink = (relative) => relative.replaceAll("\\", "/").split("/").map((part) => encodeURIComponent(part)).join("/");

/**
 * Writes the handbook pages to `outputDir` (replacing an earlier handbook).
 * With `catalog` (the object catalog's folder, as `bca export --view catalog`
 * writes it), object names link to their catalog pages.
 * @returns { outputDirectory, pages: [file], objects, linked }
 */
export async function generateHandbook(input, values = {}) {
  const outputDirectory = path.resolve(values.outputDir ?? values.output ?? "docs/handbook");
  let linkTo = values.linkTo;
  let linked = 0;
  let model;
  if (!linkTo && values.catalog) {
    const catalog = path.resolve(values.catalog);
    const cache = new Map();
    const { paths } = await catalogLayout(input, values, { cache });
    model = [...cache.values()][0];
    linkTo = (object) => {
      const page = paths.get(object.key);
      if (!page) return undefined;
      linked++;
      return encodeLink(path.relative(outputDirectory, path.join(catalog, page)));
    };
  }
  const { pages, objects } = await renderHandbook(input, { ...values, linkTo }, { model });
  await assertReplaceable(outputDirectory);
  await fs.mkdir(outputDirectory, { recursive: true });
  for (const name of await fs.readdir(outputDirectory)) {
    if (name.endsWith(".md")) await fs.rm(path.join(outputDirectory, name), { force: true });
  }
  for (const page of pages) await fs.writeFile(path.join(outputDirectory, page.file), `${MARKER}\n\n${page.content}`);
  return { outputDirectory, pages: pages.map(({ file }) => file), objects, linked };
}
