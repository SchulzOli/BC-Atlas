// The BC Atlas ontology on its own, as published at its IRI: the RDF files
// (ontology.ttl, .owl, .rdf, .nt, .jsonld) and the page that documents every
// term, with an anchor per term so https://...ontology#Table lands on Table.
import { COMMENT, LABEL, ONTOLOGY, PREFIXES, vocabulary } from "./vocabulary.js";
import { serializeGraph } from "./serialize.js";

// Extension -> [serializer, media type]. GitHub Pages serves these types by extension.
export const ONTOLOGY_FILES = Object.freeze({
  ttl: ["ttl", "text/turtle"],
  owl: ["owl", "application/rdf+xml"],
  rdf: ["rdf", "application/rdf+xml"],
  nt: ["nt", "application/n-triples"],
  jsonld: ["jsonld", "application/ld+json"]
});

/** The ontology as one RDF document in the syntax of an extension. */
export function ontologyFile(extension, version) {
  let text = "";
  serializeGraph(ONTOLOGY_FILES[extension][0], vocabulary({ version }), (chunk) => { text += chunk; });
  return text;
}

const one = (block, property) => block.props.find(([p]) => p === property)?.[1];
const local = (value) => value.slice(PREFIXES.bca.length);
const cell = (value) => String(value ?? "").replaceAll("|", "\\|");

/** A term as a link to its anchor on this page, or as a prefixed name outside it. */
function link(value) {
  if (!value) return "";
  if (value.startsWith(PREFIXES.bca)) return `[\`bca:${local(value)}\`](#${local(value)})`;
  return `\`xsd:${value.slice(PREFIXES.xsd.length)}\``;
}

/** The documentation page of the ontology, in Markdown. */
export function ontologyMarkdown(version, website) {
  const blocks = [...vocabulary({ version })];
  const header = blocks.find(({ s }) => s === ONTOLOGY);
  const is = (type) => (block) => block.types.includes(`${PREFIXES.owl}${type}`);
  const parent = (block, property) => one(block, `${PREFIXES.rdfs}${property}`)?.iri;
  const anchor = (block) => `<a id="${local(block.s)}"></a>\`bca:${local(block.s)}\``;
  const label = (block) => cell(one(block, LABEL)?.value);
  const comment = (block) => cell(one(block, COMMENT)?.value);
  const classes = blocks.filter(is("Class"));
  const objectProperties = blocks.filter(is("ObjectProperty"));
  const relations = objectProperties.filter((block) => parent(block, "subPropertyOf") === `${PREFIXES.bca}dependsOn`);
  const others = objectProperties.filter((block) => !relations.includes(block));
  const data = blocks.filter(is("DatatypeProperty"));
  const files = Object.keys(ONTOLOGY_FILES);
  const names = { ttl: "Turtle", owl: "OWL (RDF/XML)", rdf: "RDF/XML", nt: "N-Triples", jsonld: "JSON-LD" };
  return [
    "# BC Atlas ontology",
    "",
    "<!-- Generated by scripts/generate-docs.js. Do not edit this file. -->",
    "",
    `${header.props.find(([p]) => p === COMMENT)[1].value} The vocabulary of the`,
    "[knowledge graph export](../knowledge-graph.md) (`bca export --view knowledge-graph`).",
    "",
    "| | |",
    "| --- | --- |",
    `| Ontology IRI | \`${ONTOLOGY}\` |`,
    `| Namespace | \`${PREFIXES.bca}\` (prefix \`bca:\`) |`,
    `| Version | ${version} |`,
    "| License | MIT |",
    `| Download | ${files.map((extension) => `[${names[extension]}](${website}ontology.${extension})`).join(" · ")} |`,
    "",
    "Every export already contains these terms, so a graph loads without this",
    "page. Each term's IRI leads to its row here: `bca:Table` is",
    `\`${PREFIXES.bca}Table\`. Tools that need RDF take one of the`,
    "downloads; in Protégé, **File › Open from URL** with the OWL link.",
    "",
    "## Classes",
    "",
    "Every AL object is an instance of its type's class, which is a subclass of",
    "`bca:Object` (extensions also of `bca:ExtensionObject`).",
    "",
    "| Class | Label | Subclass of | Description |",
    "| --- | --- | --- | --- |",
    ...classes.map((block) => `| ${anchor(block)} | ${label(block)} | ${link(parent(block, "subClassOf"))} | ${comment(block)} |`),
    "",
    "## Relations between objects",
    "",
    "One property per kind of relation the analysis finds, each a sub-property",
    "of [`bca:dependsOn`](#dependsOn): a store with RDFS inference answers",
    "`?a bca:dependsOn ?b` for all of them. Each relation is also a",
    "[`bca:Relation`](#Relation) with its evidence, unless the export used",
    "`--no-evidence`.",
    "",
    "| Property | Label | Description |",
    "| --- | --- | --- |",
    ...relations.map((block) => `| ${anchor(block)} | ${label(block)} | ${comment(block)} |`),
    "",
    "## Other object properties",
    "",
    "| Property | Label | Domain | Range | Description |",
    "| --- | --- | --- | --- | --- |",
    ...others.map((block) => `| ${anchor(block)} | ${label(block)} | ${link(parent(block, "domain"))} | ${link(parent(block, "range"))} | ${comment(block)} |`),
    "",
    "## Data properties",
    "",
    "| Property | Label | Type | Description |",
    "| --- | --- | --- | --- |",
    ...data.map((block) => `| ${anchor(block)} | ${label(block)} | ${link(parent(block, "range"))} | ${comment(block)} |`),
    ""
  ].join("\n");
}
