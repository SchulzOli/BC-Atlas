// The layered documentation: the system explained from the whole down to each
// procedure, one page per part, each with a picture, generated from the atlas
// (src/app/atlas.js), the one graph the view shows.
//
//   Layer 0  README.md                 the system
//   Layer 1  apps/<app>.md             each app and its objects
//   Layer 2  components/<name>.md      each component of the architecture
//   Layer 3  namespaces/<name>.md      each namespace
//   Layer 4  objects/<object>.md       each object: what it is, uses, and is used by
//   Layer 5  (inside the object page)  its procedures, triggers, and events, and what each does
//   across   lenses/<lens>.md          the other sides of the same system (data, calls, events, ...)
//            stories/<story>.md        the generated walks through the graph
//            findings.md               what the checks found, on what
//            atlas.json, layers.json   the graph itself, and what this folder holds
//
// The same source gives the same files, byte for byte: nothing in them says
// when they were written. That is what lets them be kept in sync (see
// src/commands/layers.js) and compared between states of the source.
import "./ui/scene.js";
import { renderSnapshotHtml } from "./snapshot.js";
import { renderView } from "./view.js";

const S = globalThis.BCA_SCENE;

export const LAYERS_SCHEMA = "bc-atlas.layers/1";
/** Above this many objects, pictures of single objects are left out unless asked for. */
const MAX_OBJECT_PICTURES = 400;
const HOLDERS = [["app", "apps", "App", 1], ["component", "components", "Component", 2], ["module", "namespaces", "Namespace", 3]];
const SEVERITIES = ["error", "warning", "info"];

const slug = (text) => String(text).toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/gu, "-").replace(/^-|-$/gu, "") || "unnamed";
const cell = (value) => String(value ?? "").replaceAll("\\", "\\\\").replaceAll("|", "\\|").replace(/\s*\n\s*/gu, " ");
const plural = (count, word) => `${Number(count).toLocaleString("en-US")} ${word}${count === 1 ? "" : "s"}`;
/** A Markdown table; a column whose name ends with ":" holds numbers and is set to the right. */
const table = (head, rows) => (rows.length ? [
  `| ${head.map((column) => column.replace(/:$/u, "")).join(" | ")} |`,
  `| ${head.map((column) => (column.endsWith(":") ? "---:" : "---")).join(" | ")} |`,
  ...rows.map((row) => `| ${row.map((value) => String(value ?? "").replace(/(?<!\\)\|/gu, "\\|").replace(/\s*\n\s*/gu, " ")).join(" | ")} |`)
].join("\n") : "");

/** A path from one page of the folder to another. */
function relative(from, to) {
  const here = from.split("/").slice(0, -1);
  const there = to.split("/");
  let shared = 0;
  while (shared < here.length && shared < there.length - 1 && here[shared] === there[shared]) shared++;
  return [...new Array(here.length - shared).fill(".."), ...there.slice(shared)].join("/") || ".";
}

/**
 * What a state of the source is called in the pages.
 * @param state undefined for the working tree, or { label, ref, commit, date } for a commit, tag, or release
 */
const stateLine = (state) => (state
  ? `The source as it was at **${state.label}** (commit \`${String(state.commit).slice(0, 10)}\` of ${String(state.date).slice(0, 10)}).`
  : "The source as it is now.");
const FOOTER = "_Generated by BC Atlas from the AL source. Do not edit; run `bca layers` again._";

/**
 * Builds every file of the layered documentation.
 * @param workspace the analyzed project (src/app/workspace.js)
 * @param options { pictures: "auto" | "all" | "none", state, view } pictures of single objects are left out above
 *   400 objects with "auto"; state names a commit, tag, or release the workspace is a checkout of; with view,
 *   the folder also holds view.html, the BC Atlas view of this state as one offline file
 * @returns { files: Map<path, text>, manifest, atlas }
 */
export async function buildLayers(workspace, { pictures = "auto", state, view = false } = {}) {
  const atlas = await workspace.atlas();
  const found = S.index(atlas);
  const files = new Map();
  const at = (id) => (found.position.has(id) ? atlas.nodes[found.position.get(id)] : undefined);
  const objects = atlas.nodes.filter((node) => node.kind === "object" && !node.external);
  const objectPictures = pictures === "all" || (pictures === "auto" && objects.length <= MAX_OBJECT_PICTURES);

  // Where the page of each node is.
  const pageOf = new Map();
  const taken = new Set();
  const place = (node, folder, name) => {
    let file = `${folder}/${name}.md`;
    for (let count = 2; taken.has(file); count++) file = `${folder}/${name}-${count}.md`;
    taken.add(file);
    pageOf.set(node.id, file);
  };
  for (const [kind, folder] of HOLDERS) {
    for (const node of atlas.nodes) if (node.kind === kind && !(kind === "app" && node.origin && node.origin !== "This workspace")) place(node, folder, slug(node.label));
  }
  for (const node of objects) place(node, "objects", slug([node.type, node.objectId, node.label].filter(Boolean).join(" ")));
  const lensPage = (lens) => `lenses/${slug(lens.id)}.md`;
  const storyPage = (story) => `stories/${slug(story.id)}.md`;

  const name = (node) => (node.kind === "object" ? `${node.type} ${node.objectId ? `${node.objectId} ` : ""}${node.label}` : node.label);
  /** A node as a link from a page, or its name when it has no page (an object of another app). */
  const link = (node, from, text = node.label) => (pageOf.has(node.id) ? `[${cell(text)}](${relative(from, pageOf.get(node.id))})` : `${cell(text)}${node.kind === "object" && node.external ? " (other app)" : ""}`);
  const findingsOn = (indexes) => {
    const seen = new Set();
    for (const index of indexes) for (const finding of found.findingsOf.get(index) ?? []) seen.add(finding);
    return [...seen].sort((a, b) => SEVERITIES.indexOf(a.severity) - SEVERITIES.indexOf(b.severity) || a.rule.localeCompare(b.rule) || a.message.localeCompare(b.message));
  };
  const findingLines = (findings, from) => findings.map((finding) => {
    const on = finding.nodes.map((index) => atlas.nodes[index]).filter((node) => node.kind !== "rule");
    return `- **${finding.severity}** \`${finding.rule}\`: ${finding.message}${finding.fix ? `\n  - Fix: ${finding.fix}` : ""}${on.length ? `\n  - On: ${on.map((node) => link(node, from)).join(", ")}` : ""}${finding.file ? `\n  - Source: \`${finding.file}${finding.line ? `:${finding.line}` : ""}\`` : ""}`;
  });
  const picture = async (file, options) => {
    if (pictures === "none") return "";
    const drawn = await renderView(workspace, { ...options, form: "diagram", format: "svg" });
    if (!drawn.scene?.entries.length) return "";
    const target = file.replace(/\.md$/u, ".svg");
    files.set(target, drawn.content);
    return `![${cell(drawn.scene.title)}](${relative(file, target)})\n`;
  };
  const worst = (findings) => (findings.length ? `${findings.length} (${findings[0].severity})` : "");
  const indexOf = (node) => found.position.get(node.id);

  // ------------------------------------------------------------ Layer 4 and 5
  const memberOf = { app: new Map(), component: new Map(), module: new Map() };
  for (const node of objects) {
    const picked = { app: node.app, component: node.component, module: node.namespace ? `${node.app}\n${node.namespace}` : undefined };
    for (const [kind, key] of Object.entries(picked)) if (key) (memberOf[kind].get(key) ?? memberOf[kind].set(key, []).get(key)).push(node);
  }
  const holderKey = (node) => (node.kind === "module" ? `${node.app}\n${node.label}` : node.label);
  const holderOf = (kind, node) => atlas.nodes.find((candidate) => candidate.kind === kind && pageOf.has(candidate.id)
    && holderKey(candidate) === (kind === "module" ? `${node.app}\n${node.namespace}` : kind === "app" ? node.app : node.component));
  const crumbs = (node, from) => [`[System](${relative(from, "README.md")})`, ...HOLDERS.map(([kind]) => holderOf(kind, node)).filter(Boolean).map((holder) => link(holder, from))].join(" › ");

  // What objects do with each other, by object.
  const out = new Map();
  const into = new Map();
  for (const [from, to, relation] of atlas.edges) {
    const a = atlas.nodes[from];
    const b = atlas.nodes[to];
    if (a.kind !== "object" || b.kind !== "object") continue;
    const kind = atlas.relations[relation].kind;
    (out.get(a.id) ?? out.set(a.id, []).get(a.id)).push([kind, b]);
    (into.get(b.id) ?? into.set(b.id, []).get(b.id)).push([kind, a]);
  }
  const grouped = (pairs, from) => {
    const byKind = new Map();
    for (const [kind, node] of pairs) (byKind.get(kind) ?? byKind.set(kind, []).get(kind)).push(node);
    return [...byKind].sort(([a], [b]) => a.localeCompare(b)).map(([kind, nodes]) => `- **${kind}** ${[...new Set(nodes)].sort((a, b) => name(a).localeCompare(name(b))).map((node) => link(node, from, name(node))).join(", ")}`);
  };

  for (const node of objects) {
    const file = pageOf.get(node.id);
    const within = await workspace.inside(node.id);
    const members = within?.nodes ?? [];
    const does = new Map();
    for (const [from, to, relation] of within?.edges ?? []) {
      const kind = within.relations[relation].kind;
      if (kind === "contains") continue;
      const target = at(to) ?? members.find(({ id }) => id === to);
      if (target) (does.get(from) ?? does.set(from, []).get(from)).push(`${kind} ${target.kind === "member" ? `\`${target.label}\`` : link(target, file)}`);
    }
    const facts = [["Type", node.type], ["ID", node.objectId], ["App", node.app], ["Component", node.component], ["Namespace", node.namespace], ["Visibility", node.level && `${node.level}${node.canBe ? `; can be ${node.canBe}` : ""}`], ["Lines", node.lines], ["Procedures", node.procedures], ["Complexity", node.complexity], ["Uses", node.uses], ["Used by", node.usedBy],
      ["Source", node.file && (node.url ? `[\`${node.file}${node.line ? `:${node.line}` : ""}\`](${node.url})` : `\`${node.file}${node.line ? `:${node.line}` : ""}\``)]].filter(([, value]) => value !== undefined && value !== "");
    const findings = findingsOn([indexOf(node)]);
    const image = objectPictures ? await picture(file, { inside: node.id }) : "";
    // What it is, in a sentence.
    const verbs = (pairs) => [...new Set(pairs.map(([kind]) => kind))].sort();
    const others = (pairs) => new Set(pairs.map(([, other]) => other.id)).size;
    const sentence = `The ${node.type} ${node.label}${node.app ? ` of the app ${node.app}` : ""}${node.component ? `, in the component ${node.component}` : ""}`
      + `${members.length ? `, has ${plural(members.length, "member")}${node.lines ? ` in ${plural(node.lines, "line")}` : ""}` : node.lines ? `, has ${plural(node.lines, "line")}` : ""}. `
      + `${out.has(node.id) ? `It ${verbs(out.get(node.id)).join(", ")} ${plural(others(out.get(node.id)), "other object")}` : "It uses no other object"}, and `
      + `${into.has(node.id) ? `${plural(others(into.get(node.id)), "object")} ${others(into.get(node.id)) === 1 ? "uses" : "use"} it` : "nothing in this workspace uses it"}.`;
    files.set(file, [
      `# ${name(node)}`, "", crumbs(node, file), "",
      ...(node.about ?? node.caption ? [node.about ?? node.caption, ""] : []),
      sentence, "",
      table(["Fact", "Value"], facts), "",
      ...(image ? [image] : []),
      ...(members.length ? ["## Inside", "", "Layer 5: its procedures, triggers, and events, and what each of them does.", "",
        table(["Member", "Kind", "Lines:", "Complexity:", "Does"], members.map((member) => [`\`${member.header ?? member.label}\``, member.type, member.lines ?? "", member.complexity ?? "", (does.get(member.id) ?? []).join("; ")])), ""] : []),
      ...(out.has(node.id) ? ["## Uses", "", ...grouped(out.get(node.id), file), ""] : []),
      ...(into.has(node.id) ? ["## Used by", "", ...grouped(into.get(node.id), file), ""] : []),
      ...(findings.length ? ["## Findings", "", ...findingLines(findings, file), ""] : []),
      FOOTER, ""
    ].join("\n"));
  }

  // ------------------------------------------------------- Layers 1, 2, and 3
  const holderRows = new Map();
  for (const [kind, , title, layer] of HOLDERS) {
    const rows = [];
    for (const node of atlas.nodes.filter((candidate) => candidate.kind === kind && pageOf.has(candidate.id))) {
      const file = pageOf.get(node.id);
      const own = (memberOf[kind].get(holderKey(node)) ?? []).slice().sort((a, b) => name(a).localeCompare(name(b)));
      const index = indexOf(node);
      const related = (direction, from = file) => atlas.edges.filter((edge) => edge[direction ? 0 : 1] === index && atlas.nodes[edge[direction ? 1 : 0]].kind === kind)
        .map((edge) => `${atlas.relations[edge[2]].kind} ${link(atlas.nodes[edge[direction ? 1 : 0]], from)}`);
      const types = new Map();
      for (const object of own) types.set(object.type, (types.get(object.type) ?? 0) + 1);
      // What it is, in a sentence.
      const sentence = `The ${title.toLowerCase()} ${node.label} holds ${plural(own.length, "object")}${own.length ? ` (${[...types].sort(([, a], [, b]) => b - a).map(([type, count]) => plural(count, type)).join(", ")})` : ""}${node.layer ? ` in ${node.layer.toLowerCase()}` : ""}. `
        + `${related(true).length ? `It depends on ${plural(related(true).length, `other ${title.toLowerCase()}`)}` : `It depends on no other ${title.toLowerCase()}`}, and ${related(false).length ? `${plural(related(false).length, `other ${title.toLowerCase()}`)} depend${related(false).length === 1 ? "s" : ""} on it` : "none depends on it"}.`;
      const findings = findingsOn([index, ...own.map(indexOf)]);
      const facts = [["Layer", node.layer], ["Publisher", node.publisher], ["Version", node.version], ["App", kind === "module" ? node.app : undefined], ["Objects", own.length], ["Instability", node.instability], ["Can be an app", node.canBeApp]].filter(([, value]) => value !== undefined && value !== "");
      const image = await picture(file, { inside: node.id });
      const parts = kind === "app" ? HOLDERS.slice(1).map(([inner, , innerTitle]) => [innerTitle, atlas.nodes.filter((candidate) => candidate.kind === inner && pageOf.has(candidate.id)
        && own.some((object) => holderKey(candidate) === (inner === "module" ? `${object.app}\n${object.namespace}` : object.component)))]).filter(([, nodes]) => nodes.length) : [];
      files.set(file, [
        `# ${title} ${node.label}`, "", `[System](${relative(file, "README.md")}) › Layer ${layer}: ${title.toLowerCase()}s`, "",
        sentence, "",
        table(["Fact", "Value"], facts), "",
        ...(image ? [image] : []),
        ...parts.flatMap(([innerTitle, nodes]) => [`## ${innerTitle}s`, "", nodes.map((inner) => link(inner, file)).join(", "), ""]),
        ...(related(true).length ? ["## Depends on", "", ...related(true).map((line) => `- ${line}`), ""] : []),
        ...(related(false).length ? ["## Used by", "", ...related(false).map((line) => `- ${line}`), ""] : []),
        "## Objects", "",
        table(["Object", "Type", "ID", kind === "module" ? "Component" : "Namespace", "Lines:", "Uses:", "Used by:", "Findings"], own.map((object) => [link(object, file), object.type, object.objectId ?? "", (kind === "module" ? object.component : object.namespace) ?? "", object.lines ?? "", object.uses ?? "", object.usedBy ?? "", worst(findingsOn([indexOf(object)]))])), "",
        ...(findings.length ? ["## Findings", "", ...findingLines(findings, file), ""] : []),
        FOOTER, ""
      ].join("\n"));
      rows.push([link(node, "README.md"), node.layer ?? node.version ?? node.app ?? "", own.length, related(true, "README.md").join(", "), worst(findings)]);
    }
    holderRows.set(kind, rows);
  }

  // ---------------------------------------------------------------- across
  const lensRows = [];
  for (const lens of atlas.lenses) {
    const file = lensPage(lens);
    const text = await renderView(workspace, { lens: lens.id, format: "md" });
    const image = await picture(file, { lens: lens.id });
    const lines = text.content.split("\n");
    // The page of a lens is what the view exports for it, with its picture and the way back.
    const body = lines.filter((line) => !line.startsWith("_Generated by BC Atlas"));
    body.splice(1, 0, "", `[System](${relative(file, "README.md")}) › Lenses`, ...(image ? ["", image.trimEnd()] : []));
    files.set(file, `${body.join("\n").replace(/\n{3,}/gu, "\n\n").trimEnd()}\n\n${FOOTER}\n`);
    lensRows.push([`[${cell(lens.title)}](${file})`, text.scene.entries.length, text.scene.edges.length, lens.summary]);
  }
  for (const story of atlas.stories) {
    const file = storyPage(story);
    // Without the line that names the BC Atlas that wrote it: the pages change only with the source.
    const lines = S.storyMarkdown(atlas, story).split("\n").filter((line) => !line.startsWith("_Generated by BC Atlas"));
    // A run of the simulation builds its picture step by step: the page shows it as it stands at the end.
    const image = story.build ? await picture(file, { story: story.id, step: story.steps.length }) : "";
    lines.splice(1, 0, "", `[System](${relative(file, "README.md")}) › Stories`, ...(image ? ["", image.trimEnd()] : []));
    files.set(file, `${lines.join("\n").replace(/\n{3,}/gu, "\n\n").trimEnd()}\n\n${FOOTER}\n`);
  }
  const bySeverity = SEVERITIES.map((severity) => [severity, atlas.findings.filter((finding) => finding.severity === severity)]);
  files.set("findings.md", [
    "# Findings", "", "[System](README.md) › Findings", "",
    atlas.findings.length ? `${bySeverity.map(([severity, findings]) => plural(findings.length, severity === "info" ? "info" : severity).replace("infos", "info")).join(", ")}.` : "The checks found nothing.", "",
    ...bySeverity.filter(([, findings]) => findings.length).flatMap(([severity, findings]) => [`## ${severity[0].toUpperCase()}${severity.slice(1)}`, "",
      ...findingLines(findings.slice().sort((a, b) => a.rule.localeCompare(b.rule) || a.message.localeCompare(b.message)), "findings.md"), ""]),
    FOOTER, ""
  ].join("\n"));

  // ---------------------------------------------------------------- Layer 0
  const summary = atlas.summary ?? {};
  const health = summary.health;
  const architecture = summary.architecture;
  const image = await picture("README.md", { lens: atlas.lenses[0]?.id });
  if (files.has("README.svg")) {
    files.set("system.svg", files.get("README.svg"));
    files.delete("README.svg");
  }
  const counts = { apps: holderRows.get("app").length, components: holderRows.get("component").length, namespaces: holderRows.get("module").length, objects: objects.length, relations: summary.relations ?? atlas.edges.length };
  files.set("README.md", [
    `# ${atlas.title}`, "", stateLine(state), "",
    `${plural(counts.objects, "object")} in ${plural(counts.apps, "app")}, ${plural(counts.relations, "relation")}.${health ? ` Health ${health.passed ? "passed" : "failed"}: ${plural(health.error, "error")}, ${plural(health.warning, "warning")}, ${health.info} info.` : ""}${architecture?.components ? ` Architecture (${architecture.mode}): ${plural(architecture.components, "component")}, ${plural(architecture.violations ?? 0, "dependency").replace("dependencys", "dependencies")} the wrong way.` : ""}`, "",
    ...(image ? [image.replace("README.svg", "system.svg")] : []),
    "## Layers", "", "The system from the whole down to each procedure. Every page links one layer up and one layer down.", "",
    table(["Layer", "What", "Count:", "Where"], [
      ["0", "System", 1, "this page"],
      ["1", "Apps", counts.apps, "[below](#apps)"],
      ["2", "Components", counts.components, counts.components ? "[below](#components)" : "none: no architecture is set or proposed"],
      ["3", "Namespaces", counts.namespaces, counts.namespaces ? "[below](#namespaces)" : "none: the objects have no namespace"],
      ["4", "Objects", counts.objects, "from the pages of layers 1 to 3"],
      ["5", "Procedures, triggers, and events", "", "inside the page of each object"]
    ]), "",
    ...[["app", "Apps", "Version"], ["component", "Components", "Layer"], ["module", "Namespaces", "App"]].flatMap(([kind, title, fact]) => (holderRows.get(kind).length
      ? [`## ${title}`, "", table([title.slice(0, -1), fact, "Objects:", "Depends on", "Findings"], holderRows.get(kind)), ""] : [])),
    "## Lenses", "", "The other sides of the same system: each lens is a part of the one graph.", "", table(["Lens", "Nodes:", "Relations:", "Shows"], lensRows), "",
    ...(atlas.stories.length ? ["## Stories", "", "Walks through the system, step by step.", "", ...atlas.stories.map((story) => `- [${cell(story.title)}](${storyPage(story)}): ${story.summary}`), ""] : []),
    "## Findings", "", atlas.findings.length ? `[${bySeverity.map(([severity, findings]) => `${findings.length} ${severity}${severity !== "info" && findings.length !== 1 ? "s" : ""}`).join(", ")}](findings.md).` : "The checks found nothing.", "",
    "## Read from", "", table(["Source", "What"], atlas.sources ?? []), "",
    `The graph itself is in [atlas.json](atlas.json)${view ? ", and [view.html](view.html) is the BC Atlas view of it: every lens, finding, and story, to look at and to click through" : ""}; [layers.json](layers.json) lists what this folder holds.`, "",
    FOOTER, ""
  ].join("\n"));

  // The graph itself, without what changes from run to run.
  const { updatedAt: _updatedAt, live: _live, version: _version, ...graph } = atlas;
  files.set("atlas.json", `${JSON.stringify(graph, null, 1)}\n`);
  // The view of this state, to open in a browser. It holds the BC Atlas that wrote it, so it is not compared.
  if (view) files.set("view.html", (await renderSnapshotHtml(workspace, { generatedAt: state?.date })).html);
  const manifest = {
    schema: LAYERS_SCHEMA,
    title: atlas.title,
    state: state ? { label: state.label, ref: state.ref, commit: state.commit, date: state.date } : "working tree",
    counts: { ...counts, findings: Object.fromEntries(bySeverity.map(([severity, findings]) => [severity, findings.length])) },
    files: [...files.keys(), "layers.json"].sort()
  };
  files.set("layers.json", `${JSON.stringify(manifest, null, 2)}\n`);
  return { files, manifest, atlas };
}

/**
 * What changed between two states of the source, from their graphs (atlas.json).
 * @returns { added, removed, changed: [names], relations: { added, removed }, others: { added, removed }, findings: { new, fixed: [text] } }
 */
export function compareStates(before, after) {
  const own = (atlas) => new Map(atlas.nodes.filter((node) => node.kind === "object" && !node.external).map((node) => [node.id, node]));
  const name = (node) => `${node.type} ${node.objectId ? `${node.objectId} ` : ""}${node.label}`;
  const relations = (atlas) => {
    const set = new Set();
    const byObject = new Map();
    for (const [from, to, relation] of atlas.edges) {
      const a = atlas.nodes[from];
      const b = atlas.nodes[to];
      if (a.kind !== "object" || b.kind !== "object") continue;
      const key = `${a.id}\n${b.id}\n${atlas.relations[relation].kind}`;
      set.add(key);
      (byObject.get(a.id) ?? byObject.set(a.id, new Set()).get(a.id)).add(key);
    }
    return { set, byObject };
  };
  const [was, is] = [own(before), own(after)];
  const [old, now] = [relations(before), relations(after)];
  const facts = (node) => [node.lines, node.procedures, node.complexity, node.level, node.component, node.namespace].join("\n");
  const same = (a, b) => a.size === b.size && [...a].every((key) => b.has(key));
  const findings = (atlas) => new Map(atlas.findings.map((finding) => [`${finding.rule}\n${finding.message}`, `${finding.severity} ${finding.rule}: ${finding.message}`]));
  const [oldFindings, newFindings] = [findings(before), findings(after)];
  const other = (atlas) => new Map(atlas.nodes.filter((node) => !["object", "rule", "module", "app"].includes(node.kind)).map((node) => [node.id, `${node.kind} ${node.label}`]));
  const [otherWas, otherNow] = [other(before), other(after)];
  return {
    added: [...is].filter(([id]) => !was.has(id)).map(([, node]) => name(node)).sort(),
    removed: [...was].filter(([id]) => !is.has(id)).map(([, node]) => name(node)).sort(),
    changed: [...is].filter(([id, node]) => was.has(id) && (facts(node) !== facts(was.get(id)) || !same(old.byObject.get(id) ?? new Set(), now.byObject.get(id) ?? new Set()))).map(([, node]) => name(node)).sort(),
    relations: { added: [...now.set].filter((key) => !old.set.has(key)).length, removed: [...old.set].filter((key) => !now.set.has(key)).length },
    // What is not an object: components, process tests, people, requirements, recordings.
    others: { added: [...otherNow].filter(([id]) => !otherWas.has(id)).map(([, text]) => text).sort(), removed: [...otherWas].filter(([id]) => !otherNow.has(id)).map(([, text]) => text).sort() },
    findings: { new: [...newFindings].filter(([key]) => !oldFindings.has(key)).map(([, text]) => text).sort(), fixed: [...oldFindings].filter(([key]) => !newFindings.has(key)).map(([, text]) => text).sort() }
  };
}

/** The changes between two states as Markdown lines, or one line when nothing changed. */
export function changesMarkdown(changes) {
  const list = (title, items) => (items.length ? [`- **${title}** (${items.length}): ${items.slice(0, 40).map(cell).join(", ")}${items.length > 40 ? `, and ${items.length - 40} more` : ""}`] : []);
  const lines = [
    ...list("Objects added", changes.added), ...list("Objects removed", changes.removed), ...list("Objects changed", changes.changed),
    ...(changes.relations.added || changes.relations.removed ? [`- **Relations**: ${changes.relations.added} added, ${changes.relations.removed} removed`] : []),
    ...list("Also new", changes.others?.added ?? []), ...list("Also gone", changes.others?.removed ?? []),
    ...list("New findings", changes.findings.new), ...list("Findings fixed", changes.findings.fixed)
  ];
  return lines.length ? lines : ["- Nothing that BC Atlas reads from the source changed."];
}

/**
 * The page that lists the recorded states of the source, the newest first, and what changed from each to the next.
 * @param states [{ folder, manifest, atlas }] from the oldest to the newest
 * @param current { manifest, atlas } the working tree, when it is documented next to the history
 */
export function historyIndex(states, current) {
  const row = (label, manifest, where) => [where ? `[${cell(label)}](${where})` : cell(label), manifest.state?.commit ? `\`${String(manifest.state.commit).slice(0, 10)}\`` : "", manifest.state?.date ? String(manifest.state.date).slice(0, 10) : "", manifest.counts.objects, manifest.counts.relations, SEVERITIES.map((severity) => manifest.counts.findings[severity] ?? 0).join(" / ")];
  const newest = states.slice().reverse();
  const sections = [];
  if (current && states.length) sections.push(`## Now, since ${states.at(-1).manifest.state.label}`, "", ...changesMarkdown(compareStates(states.at(-1).atlas, current.atlas)), "");
  newest.forEach((entry, index) => {
    const before = newest[index + 1];
    sections.push(`## ${entry.manifest.state.label}${before ? `, since ${before.manifest.state.label}` : ""}`, "",
      ...(before ? changesMarkdown(compareStates(before.atlas, entry.atlas)) : ["- The first recorded state."]), "");
  });
  return [
    "# History", "", `${current ? "[System](../README.md) › History\n\n" : ""}The system as it was at ${plural(states.length, "recorded state")} of the source: commits, tags, or releases. Each has the same layered documentation as the source of today.`, "",
    table(["State", "Commit", "Date", "Objects:", "Relations:", "Errors / warnings / info"], [
      ...(current ? [row("Now (working tree)", current.manifest, "../README.md")] : []),
      ...newest.map((entry) => row(entry.manifest.state.label, entry.manifest, `${entry.folder}/README.md`))
    ]), "",
    ...sections,
    "_Generated by BC Atlas. Add a state with `bca layers --at <commit, tag, or release>`._", ""
  ].join("\n");
}
