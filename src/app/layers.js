  // The graph itself, without what changes from run to run.
  const { updatedAt: _updatedAt, live: _live, version: _version, ...written } = atlas;
  files.set("atlas.json", `${JSON.stringify(written, null, 1)}\n`);
  // The view of this state, to open in a browser. It holds the BC Atlas that wrote it, so it is not compared.
  if (view) files.set("view.html", (await renderSnapshotHtml(workspace)).html);
  // The pages as the profile wants them: left out, named, cut, titled, translated, laid out.
  const profiled = applyProfile(files, pages, pictureOf, profile, { system: atlas.title });
  files = profiled.files;
  const manifest = {
    schema: LAYERS_SCHEMA,
    title: atlas.title,
    ...(profile?.name ? { profile: profile.name } : {}),
    // Where to start, when it is not README.md.
    ...(profiled.fixed.readme === "README.md" ? {} : { start: profiled.fixed.readme ?? null }),
    counts: { ...counts, findings: Object.fromEntries(bySeverity.map(([severity, findings]) => [severity, findings.length])) },
    files: [...files.keys(), "layers.json"].sort(),
    // The page of every object, so other documentation can link to it (bca docs generate).
    objects: objects.filter((node) => pageOf.has(node.id) && profiled.moved.has(pageOf.get(node.id)))
      .map((node) => ({ type: node.type, id: node.objectId, name: node.label, page: profiled.moved.get(pageOf.get(node.id)) }))
      .sort((a, b) => a.page.localeCompare(b.page))
  };
  files.set("layers.json", `${JSON.stringify(manifest, null, 2)}\n`);
  return { files, manifest, atlas, fixed: profiled.fixed };
