import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { generateHandbook } from "../src/handbook.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const warehouse = path.join(root, "examples", "warehouse-app");
const cli = path.join(root, "src", "cli.js");

test("the handbook explains the system across all objects, one question per page", async (t) => {
  const output = mkdtempSync(path.join(os.tmpdir(), "bca-handbook-"));
  t.after(() => rmSync(output, { recursive: true, force: true }));
  const result = await generateHandbook(warehouse, { outputDir: output });
  assert.deepEqual(result.pages, ["README.md", "events.md", "data.md", "permissions.md", "interfaces.md", "ui.md", "code-health.md"]);
  const page = (name) => readFileSync(path.join(output, name), "utf8");

  const readme = page("README.md");
  assert.match(readme, /^<!-- Generated by BC Atlas \(handbook\)/u);
  assert.match(readme, /# BC Atlas Warehouse Example: system handbook/u);
  for (const file of result.pages.slice(1)) assert.ok(readme.includes(`(./${file})`), `README links ${file}`);
  assert.match(readme, /\| Codeunit \| 3 \|/u);

  // The subscriber is found through the event it names.
  assert.match(page("events.md"), /\| Codeunit 50101 Warehouse Processor \| `OnRequestProcessed` \| integration \|  \| Codeunit 50120 Warehouse Notifications \(`NotifyRequestProcessed`\) \|/u);
  // Insert, modify, delete, read per writer; the page that shows the table.
  assert.match(page("data.md"), /\| Table 50100 Warehouse Request \|  \| CustomerContent \| 3 \| Warehouse Processor \(MR\), WarehouseUITests \(IDR\) \| Warehouse Requests \| Warehouse Requests \|/u);
  assert.match(page("permissions.md"), /\| Table 50100 Warehouse Request \| tabledata \| RIMD \|/u);
  assert.match(page("interfaces.md"), /\| Codeunit 50101 Warehouse Processor \| Warehouse Handler::Default \|/u);
  assert.match(page("ui.md"), /## Lists[\s\S]*\| Page 50110 Warehouse Requests \| Warehouse Requests \| List \| Warehouse Request \| All \|/u);
  const health = page("code-health.md");
  assert.match(health, /## Most complex procedures/u);
  assert.match(health, /0 of 3 public procedures of public objects \(the API other apps can call\) have a `\/\/\/` summary/u, "internal objects (the UI tests) are not API");

  // Generating again replaces the earlier handbook; a foreign folder is never touched.
  await generateHandbook(warehouse, { outputDir: output });
  const foreign = mkdtempSync(path.join(os.tmpdir(), "bca-handbook-foreign-"));
  t.after(() => rmSync(foreign, { recursive: true, force: true }));
  writeFileSync(path.join(foreign, "notes.md"), "mine");
  await assert.rejects(generateHandbook(warehouse, { outputDir: foreign }), /was not written by bca export --view handbook/u);
  assert.equal(readFileSync(path.join(foreign, "notes.md"), "utf8"), "mine");
});

test("bca export --view handbook and the bca run handbook task write the handbook", (t) => {
  const directory = mkdtempSync(path.join(os.tmpdir(), "bca-handbook-run-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  cpSync(warehouse, path.join(directory, "app"), { recursive: true });
  const exported = spawnSync(process.execPath, [cli, "export", path.join(directory, "app"), "--view", "handbook", "-o", path.join(directory, "out")], { encoding: "utf8" });
  assert.equal(exported.status, 0, exported.stderr);
  assert.match(exported.stdout + exported.stderr, /Handbook: 7 page\(s\) about 9 object\(s\)/u);
  assert.ok(existsSync(path.join(directory, "out", "events.md")));

  writeFileSync(path.join(directory, "app", ".bca.json"), JSON.stringify({ handbook: { outputDir: "wiki", title: "Warehouse" } }));
  const run = spawnSync(process.execPath, [cli, "run", path.join(directory, "app"), "--tasks", "handbook"], { encoding: "utf8" });
  assert.equal(run.status, 0, run.stderr + run.stdout);
  assert.match(readFileSync(path.join(directory, "app", "wiki", "README.md"), "utf8"), /# Warehouse\n/u);
});

test("with a catalog, object names in the handbook link to their catalog pages", async (t) => {
  const directory = mkdtempSync(path.join(os.tmpdir(), "bca-handbook-links-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const catalog = path.join(directory, "codegraph");
  const written = spawnSync(process.execPath, [cli, "export", warehouse, "--view", "catalog", "-o", catalog], { encoding: "utf8" });
  assert.equal(written.status, 0, written.stderr);
  const result = await generateHandbook(warehouse, { outputDir: path.join(directory, "handbook"), catalog });
  assert.ok(result.linked > 0);
  const data = readFileSync(path.join(directory, "handbook", "data.md"), "utf8");
  assert.match(data, /\| \[Table 50100 Warehouse Request\]\(\.\.\/codegraph\/table\/50100-warehouse-request\.md\) \|/u);
  // Every link points to a page the catalog wrote.
  for (const file of result.pages) {
    const content = readFileSync(path.join(directory, "handbook", file), "utf8");
    for (const [, target] of content.matchAll(/\]\((\.\.\/codegraph\/[^)]+)\)/gu)) {
      assert.ok(existsSync(path.join(directory, "handbook", decodeURIComponent(target))), `${file} links ${target}`);
    }
  }
});
