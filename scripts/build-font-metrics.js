// Writes src/diagram/metrics.js: the advance widths of Liberation Sans
// (vendor/fonts), which has the metrics of Helvetica and Arial. Diagrams size
// their boxes with it, so SVG (Arial, Helvetica, Liberation Sans), PNG
// (rendered with the vendored font), and PDF (Helvetica) all fit their text.
//
//   npm run update:font-metrics
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const RANGES = [[0x20, 0x24f], [0x2010, 0x2027], [0x2030, 0x203a], [0x2190, 0x2193], [0x20ac, 0x20ac]];
const font = (name) => opentype.parse(readFileSync(new URL(`../vendor/fonts/${name}`, import.meta.url)).buffer);

function widths(parsed) {
  const scale = 1000 / parsed.unitsPerEm;
  const table = {};
  for (const [from, to] of RANGES) {
    for (let code = from; code <= to; code++) {
      const glyph = parsed.charToGlyph(String.fromCodePoint(code));
      if (glyph.index === 0) continue;
      table[code] = Math.round(glyph.advanceWidth * scale);
    }
  }
  return table;
}

const regular = widths(font("LiberationSans-Regular.ttf"));
const bold = widths(font("LiberationSans-Bold.ttf"));
// Ranges of consecutive code points as [start, ...widths], so the file stays small.
const pack = (table) => {
  const runs = [];
  for (const code of Object.keys(table).map(Number).sort((a, b) => a - b)) {
    const last = runs.at(-1);
    if (last && last[0] + last.length - 1 === code) last.push(table[code]);
    else runs.push([code, table[code]]);
  }
  return JSON.stringify(runs);
};
writeFileSync(new URL("../src/diagram/metrics.js", import.meta.url), `// Generated by scripts/build-font-metrics.js from Liberation Sans. Do not edit.
// Advance widths in 1/1000 em, as runs of [first code point, ...widths].
export const REGULAR = ${pack(regular)};
export const BOLD = ${pack(bold)};
`);
console.log(`Wrote src/diagram/metrics.js (${Object.keys(regular).length} glyphs)`);
